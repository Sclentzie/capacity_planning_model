def write_next_dollar(sheet, assumptions, sites=None):
    """Next Dollar (spec Section 8, 6.6), priced at the AI 100% run."""
    table = next_dollar_table(assumptions, sites)
    scenario = scenarios.load_scenario(
        scenarios.scenario_dir(assumptions) / NEXT_DOLLAR_RUN
    )
    headers = [header for header, *_rest in NEXT_DOLLAR_COLUMNS]
    items = get_column_letter(headers.index("Items actually automated") + 1)
    saving = get_column_letter(
        headers.index("Saving per item, after fixed") + 1
    )

    def formula(header, row):
        if header == "Plan-year saving on the items automated":
            # Live, because it is the one figure on the tab a reader will
            # want to re-derive: per-item saving times the volume it is
            # spread over. Blank where the per-item figure is blank -
            # a formula over an empty cell would read as zero.
            if sheet[f"{saving}{row}"].value is None:
                return None
            return f"={saving}{row}*{items}{row}"
        return None

    placed = write_detail_tab(
        sheet, "Next Dollar", NEXT_DOLLAR_COLUMNS, table,
        next_dollar_notes(assumptions, scenario["name"]), formula=formula,
        total_label=(
            "PLAN-YEAR SAVING ON THE ITEMS ACTUALLY AUTOMATED IN THE "
            "AI 100% RUN"
        ),
        # NOT the baseline. The baseline runs no machine, so it could not
        # price a single row of this table - and a header saying
        # "Baseline run" would contradict the notes three rows below it,
        # on the one tab whose whole point is being labelled with its
        # basis.
        basis=f"Priced at the '{scenario['name']}' run - the full program",
    )
    sheet.freeze_panes = f"C{placed['first']}"
    return table, placed


