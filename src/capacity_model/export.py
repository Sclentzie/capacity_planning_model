# How an EMPTY input is shown, and it matters that the three are
# different. Found 11/03 by the tie-out test, which caught these being
# written as blank cells.
#
# A blank cell on a traceability tab is ambiguous in the worst way: a
# reader cannot tell whether the input is unset or whether the exporter
# failed to write it. And these inputs do not mean the same thing -
#
#   records_hub.site: ""               means CHOOSE IT FROM THE DATA
#   automation.capacity_cap...: null   means NO CAP AT ALL
#   automation.rates.only_...: []      means EVERY ELIGIBLE WORK TYPE
#
# - so collapsing them all to one empty cell would lose exactly the
# distinction this tab exists to preserve. Each says which kind of empty
# it is, and the `kind` column beside it carries the YAML type.
EMPTY_STRING = "(empty)"
EMPTY_LIST = "(empty list)"
NO_VALUE = "(null)"


def shown_input(value):
    """An input value as the Assumptions tab shows it."""
    if value is None:
        return NO_VALUE
    if isinstance(value, (list, tuple)):
        if not len(value):
            return EMPTY_LIST
        return ", ".join(str(item) for item in value)
    if isinstance(value, str) and not value.strip():
        return EMPTY_STRING
    return value


def flatten_inputs(mapping, source):
    """One row per leaf input, keyed by its dotted path in the YAML.

    A list of blocks is keyed by something STABLE about the block rather
    than by its position, so a work type reads
    `work_types.W8.handle_time_minutes` and never
    `work_types.8.handle_time_minutes` - an index that would move the
    first time somebody reordered the file, which is exactly the kind of
    reference a traceability tab must not hand out. A travel pair has no
    code of its own, so it is keyed by the two sites it joins
    (`travel.pairs.N1-N2.minutes`), which is the thing about it that
    cannot change without it becoming a different pair.
    """
    rows = []

    def label_for(item, index):
        if item.get("code"):
            return str(item["code"])
        if item.get("name"):
            return str(item["name"])
        for key in ("sites", "roles", "work_types"):
            members = item.get(key)
            if isinstance(members, (list, tuple)) and members:
                return "-".join(str(member) for member in members)
        return str(index)

    def walk(value, path):
        if isinstance(value, dict):
            for key, inner in value.items():
                walk(inner, f"{path}.{key}" if path else str(key))
        elif isinstance(value, (list, tuple)):
            blocks = [item for item in value if isinstance(item, dict)]
            if blocks and len(blocks) == len(value):
                for index, item in enumerate(value, start=1):
                    walk(item, f"{path}.{label_for(item, index)}")
            else:
                rows.append(
                    {
                        "source": source,
                        "key": path,
                        "value": shown_input(value),
                        "kind": "list",
                    }
                )
        else:
            rows.append(
                {
                    "source": source,
                    "key": path,
                    "value": shown_input(value),
                    "kind": type(value).__name__,
                }
            )

    walk(mapping, "")
    return rows


def assumptions_table(run, assumptions=None, sites=None, skills=None):
    """Every input, from all three YAML files plus the scenario, in one list."""
    assumptions = assumptions or run.get("assumptions") or config.load_assumptions()
    if sites is None:
        sites = run.get("sites")
    if sites is None:
        sites = config.load_sites()
    if skills is None:
        skills = config.load_skills()

    rows = []
    rows.extend(flatten_inputs(assumptions, "assumptions.yaml"))
    rows.extend(flatten_inputs(sites, "sites.yaml"))
    rows.extend(flatten_inputs(skills, "skills.yaml"))

    scenario = run.get("scenario") or {}
    name = scenario.get("key", "baseline")
    for key in ("name", "starts_week", "what_it_changes"):
        if key in scenario:
            rows.append(
                {
                    "source": f"scenarios/{name}.yaml",
                    "key": f"scenario.{key}",
                    "value": shown_input(scenario[key]),
                    "kind": type(scenario[key]).__name__,
                }
            )

    return pd.DataFrame(rows).reset_index(drop=True)


# ---------------------------------------------------------------------------
# The shared detail-tab writer
#
# One writer for all of them, because four hand-written writers is four
# places for the font, the freeze, the filter and the number formats to
# drift apart - and two tabs that do not match is the first thing that
# makes a workbook look unowned.
# ---------------------------------------------------------------------------


def write_detail_tab(sheet, name, columns, table, notes, formula=None,
                     total_label=None, start_row=None, filtered=True,
                     empty_note=None, basis="Baseline run"):
    """A titled, filtered, frozen table with a plan-year total row.

    `formula` is called for a column whose source is None - the live
    cells. Only TOTALS and DIFFERENCES are formulas (decided 11/03): a
    measure is always a written value, which is what lets the Section 9
    check tie the workbook to the model to the cent.
    """
    header_row = DETAIL_HEADER_ROW if start_row is None else start_row
    first = header_row + 1

    if start_row is None:
        _put(sheet, f"A{DETAIL_TITLE_ROW}", f"{name} - SYNTHETIC", TITLE_FONT)
        _put(sheet, f"A{DETAIL_NOTE_ROW}", SYNTHETIC, NOTE_FONT)
        _put(
            sheet,
            f"A{DETAIL_SOURCE_ROW}",
            f"{basis}, plan year, {len(table):,} rows. Every measure is "
            f"written by the model; only totals and differences are live "
            f"Excel formulas. Every scenario's headline measures are on "
            f"the '{SCENARIOS_TAB}' tab.",
            NOTE_FONT,
        )

    if not len(table) and empty_note:
        _put(sheet, f"A{header_row}", empty_note, NOTE_FONT, alignment=WRAP_TOP)
        sheet.row_dimensions[header_row].height = _wrapped_height(empty_note, 110, 12.0)
        sheet.column_dimensions["A"].width = 110
        return {"header_row": header_row, "first": first, "last": header_row,
                "total_row": None}

    for index, (header, _source, _fmt, width, _total) in enumerate(columns, start=1):
        letter = get_column_letter(index)
        cell = _put(
            sheet, f"{letter}{header_row}", header, HEADER_FONT,
            alignment=HEADER_ALIGN,
        )
        cell.fill = HEADER_FILL
        # WIDEN ONLY. A tab with two blocks shares its columns between
        # them, and letting the lower block win would narrow a column the
        # block above it needs - which is how a money column ends up
        # rendering as ####.
        current = sheet.column_dimensions[letter].width or 0
        sheet.column_dimensions[letter].width = max(width, current)
    sheet.row_dimensions[header_row].height = 42

    for offset, record in enumerate(table.to_dict("records")):
        row = first + offset
        for index, (header, source, number_format, _width, _total) in enumerate(
            columns, start=1
        ):
            letter = get_column_letter(index)
            if source is None:
                value = formula(header, row) if formula else None
            else:
                value = record.get(source)
            if value is None:
                continue
            if isinstance(value, float) and pd.isna(value):
                continue
            if isinstance(value, str) and value.startswith("="):
                # A formula still needs its number format. Found 11/03 by
                # the format test: the hours-gap column was writing live
                # formulas with no format at all, so Excel would have
                # shown a shortfall as -12.3456789 in General rather than
                # as (12.3) in hours.
                _put(sheet, f"{letter}{row}", value, BODY_FONT, number_format)
            elif isinstance(value, bool) or isinstance(value, str):
                _put(sheet, f"{letter}{row}", value, BODY_FONT)
            elif isinstance(value, (int, float)):
                _put(sheet, f"{letter}{row}", float(value), BODY_FONT, number_format)
            else:
                _put(sheet, f"{letter}{row}", str(value), BODY_FONT)

    last = first + len(table) - 1

    # The filter covers the header and the data and stops short of the
    # total row. A total that moves with the filter is a neat trick and a
    # terrible number to quote, because it stops being the plan-year total
    # without saying so.
    if filtered:
        last_letter = get_column_letter(len(columns))
        sheet.auto_filter.ref = f"A{header_row}:{last_letter}{last}"

    total_row = None
    if total_label:
        total_row = last + 2
        _put(sheet, f"A{total_row}", total_label, BODY_BOLD)
        for index, (_header, _source, number_format, _width, totalled) in enumerate(
            columns, start=1
        ):
            if not totalled:
                continue
            letter = get_column_letter(index)
            cell = _put(
                sheet,
                f"{letter}{total_row}",
                f"=SUM({letter}{first}:{letter}{last})",
                BODY_BOLD,
                number_format,
            )
            cell.border = UNDERLINE

    if notes:
        row = (total_row or last) + 2
        _put(sheet, f"A{row}", "HOW TO READ THIS", SECTION_FONT)
        row += 1
        note_width = sum(width for _h, _s, _f, width, _t in columns)
        for note in notes:
            _put(sheet, f"A{row}", note, NOTE_FONT, alignment=WRAP_TOP)
            sheet.row_dimensions[row].height = _wrapped_height(note, note_width, 12.0)
            row += 1

    return {"header_row": header_row, "first": first, "last": last,
            "total_row": total_row}


