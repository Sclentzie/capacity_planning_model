"""After proof of concept: earning a lower QA sample (spec 7, 11/02).

All data is SYNTHETIC, generated by this model.

THE WFM IDEA
------------
Human-in-the-loop (spec 5.5) is the part of automation nobody budgets
for. Every automated item comes back in three pieces - the exceptions the
machine could not finish, the QA sample somebody reviews, and the legal
sign-off - and those pieces are why a machine that takes 8% of the work
does not cut 8% of the hours.

Two of the three are permanent. The exception rate is a property of the
work: hard items stay hard. The legal sign-off is a property of the LAW:
where a statute says a person must decide, no amount of measured accuracy
changes that, and this module will not pretend otherwise.

The QA sample is the one piece that is a property of TRUST. It is set
high at go-live because nobody yet knows how good the machine is, and a
sample is how you find out. Once it has been measured, the sample can
come down - that is what a control chart is for, and it is the only
saving a proof of concept actually unlocks.

So this scenario answers a narrow question honestly rather than a broad
one loosely: how many hours does PROVING the automation free, as against
installing it?

WHY THE GATE IS SLOW, AND WHY THAT IS THE POINT
-----------------------------------------------
The automation's true error rate is an input (default 0.3%). Nobody
observes it. What the operation observes is the error rate in the sample
it actually reviewed, and a sample is a random draw:

    errors this week ~ Binomial(items sampled, true error rate)
    observed rate    = errors / items sampled

That single line is what makes this scenario interesting. At a 0.3% true
rate and a 0.5% target, a week sampling 300 items is fine - but a week
sampling 30 is a coin toss, because one unlucky error reads as 3.3% and
resets the clock. The gate needs the target to hold for 12 CONSECUTIVE
weeks, so the binomial noise does not merely delay the gate, it can stall
it indefinitely on a thin sample.

That is the WFM lesson, and it is the same one behind every service-level
measurement in this model: a rate measured on a small sample is mostly
noise, and a rule that reads it as fact will make decisions out of luck.

A week that sampled NOTHING is not a passing week. Before go-live there
are no automated items, so there is no reading, and "no evidence" must
never count toward a gate - otherwise the automation would clear its
proof of concept during the weeks it did not exist.

ONE PROGRAM, ONE READING
------------------------
The error rate is measured network-wide across every automated work type
rather than per row. There is one platform (spec 5.4 charges one platform
fee for exactly that reason), and a proof of concept is a decision about
that platform. Measuring per row would also make the thin rows wait
forever on their own small samples, which would be an artefact of how the
work types are cut rather than a fact about the machine.

THE FEEDBACK NOBODY NOTICES
---------------------------
Lowering the sample is not free, and the model shows why: the sample
IS the measurement. After the gate the sample halves, so the reading gets
noisier exactly when the operation has stopped worrying. This module
reports the sampled count every week so that effect is visible, and the
series is built as a forward pass - week by week, each week's sample size
depending on whether the gate had already been met - because that is the
real order of events and a vectorised version would have to assume the
answer.

Limitation, stated rather than hidden: once met, the gate stays met. The
model never raises a sample rate back up when the observed rate drifts.
A real control chart would, and it would matter most on the halved
sample.

This gate is the one spec 7 specifies, and it is deliberately not the
one a statistician would write. Logged as a future build (spec 7, Siri
11/03): judge the POOLED 12-week error rate rather than twelve separate
weekly readings, require a minimum sample before any reading counts, and
restore the full QA sample after a failed week. All three fix the same
flaw - that twelve independent small samples ask for twelve lucky
coin-flips instead of one adequate measurement - and none of them is
built here. What is built is the spec's rule, measured honestly enough
to show why it needs replacing.

WHAT THE TARGETING DOES NOT KNOW
--------------------------------
"AI targeted" (spec 7) picks its work types from the Next Dollar ranking,
which values an automated item at the FULL QA sample rate. That is left
alone deliberately: the targeting decision is made at go-live, before any
gate has been cleared, and a row that only pays on a QA discount it has
not yet earned has not been shown to pay. So the proof of concept is a
saving on a decision already made, never a reason to make a wider one.
"""

import numpy as np
import pandas as pd

from . import automation, config


# Columns of the weekly observation series, in report order.
SERIES_COLUMNS = [
    "week_index",
    "week_start",
    "period",
    "automated_items",
    "qa_rate_multiple",
    "sample_at_full_rate",
    "sampled_items",
    "errors_found",
    "observed_error_rate",
    "at_or_under_target",
    "consecutive_weeks",
    "gate_met",
    "qa_rate_lowered",
]


def settings(assumptions=None):
    """The scenario's proof-of-concept block (spec 7)."""
    assumptions = assumptions or config.load_assumptions()
    return config.scenario(assumptions)["proof_of_concept"]


def enabled(assumptions=None):
    """Whether the gate is being watched at all.

    False in the baseline and in every other scenario, so they take
    exactly the path they took before this module existed.
    """
    return bool(settings(assumptions)["enabled"])


def target_error_rate(assumptions=None):
    """The rate the automation has to hold at or under (spec 7, default 0.5%)."""
    return float(settings(assumptions)["target_error_rate"])


def weeks_to_hold(assumptions=None):
    """Consecutive weeks it has to hold for (spec 7, default 12)."""
    return int(settings(assumptions)["weeks_to_hold"])


def true_error_rate(assumptions=None):
    """The machine's real error rate - an input, and never observed.

    Illustrative at 0.3% (Siri 11/02). The sensitivity run sits it right
    on the 0.5% target, which is where the binomial noise does its worst
    work: half the weeks read high by luck alone.
    """
    return float(settings(assumptions)["true_error_rate"])


def after_gate_qa_multiple(assumptions=None):
    """What each row's QA sample rate is multiplied by after the gate.

    Spec 7 default is half of each row's rate, which is 0.5 here. Kept as
    a multiple rather than a replacement table so the rows keep their
    relative order: W7's 100% review and W3's 2% are not the same decision
    and should not become the same number.
    """
    return float(settings(assumptions)["after_gate_qa_multiple"])


def legal_requirement_changed(assumptions=None):
    """Whether the LAW changed, which is the only thing that moves sign-off.

    Default false, and it is the default for a reason (spec Section 1):
    "where a legal requirement says a person must decide, automation may
    do the prep, but every item goes to a person for the final decision."
    A measured error rate is evidence about the machine, not about the
    statute. Section 9 checks that sign-off stays at 100% unless this
    input says the requirement itself allows otherwise.
    """
    return bool(settings(assumptions)["legal_requirement_changed"])


def after_gate_sign_off_rate(assumptions=None):
    """The sign-off rate once the gate is met AND the law allows it.

    Ignored entirely while `legal_requirement_changed` is false, which is
    the default, so the number sitting here cannot leak into a run by
    itself.
    """
    return float(settings(assumptions)["after_gate_sign_off_rate"])


def seed(assumptions=None):
    """Fixed seed for the sampling draw, so every run reads the same weeks."""
    return int(settings(assumptions)["seed"])


def qa_sample_rates(assumptions=None):
    """{work type: its QA sample rate at go-live} (spec 5.5).

    Read from the automation block rather than restated, so the two can
    never disagree.
    """
    assumptions = assumptions or config.load_assumptions()
    rows = automation.settings(assumptions)["work_types"]
    return {code: float(row.get("qa_sample_rate", 0.0)) for code, row in rows.items()}


def observed_series(automated_plan, assumptions=None):
    """One row a week: what was sampled, what was found, where the gate is.

    Built as a FORWARD pass in week order. Each week's sample size depends
    on whether the gate had already been met in an earlier week, so the
    series cannot be computed in one vectorised shot without assuming its
    own answer - and the dependency is the finding, not an inconvenience.

    The random draw is consumed only in weeks that actually sampled
    something, so the sequence is fixed by the seed and by the volumes,
    not by how many empty pre-go-live weeks happen to precede them.
    """
    assumptions = assumptions or config.load_assumptions()
    if automated_plan is None or len(automated_plan) == 0:
        return pd.DataFrame(columns=SERIES_COLUMNS)

    rates = qa_sample_rates(assumptions)
    target = target_error_rate(assumptions)
    hold = weeks_to_hold(assumptions)
    truth = true_error_rate(assumptions)
    lowered_multiple = after_gate_qa_multiple(assumptions)
    rng = np.random.default_rng(seed(assumptions))

    plan = automated_plan.copy()
    plan["sample_at_full_rate"] = [
        float(items) * rates.get(code, 0.0)
        for items, code in zip(plan["automated_items"], plan["work_type"])
    ]
    weekly = (
        plan.groupby(["week_index", "week_start", "period"], as_index=False)
        .agg(
            automated_items=("automated_items", "sum"),
            sample_at_full_rate=("sample_at_full_rate", "sum"),
        )
        .sort_values("week_index")
    )

    gate, run, rows = None, 0, []
    for row in weekly.itertuples():
        # The lower rate applies from the week AFTER the gate is met, not
        # in the week it is met: that week's reading is part of the
        # evidence, so it has to be taken at the rate that was in force
        # while it was being gathered.
        lowered = gate is not None and row.week_index > gate
        multiple = lowered_multiple if lowered else 1.0

        # TWO sample figures, and the difference matters.
        #
        # `expected` is the continuous one - items x rate x multiple - and
        # it is what the HOURS are priced from, because every handle time
        # in this model is an average over a week's items and rounding it
        # would be a false precision.
        #
        # `sampled` is the whole number of files a reviewer actually
        # looked at, which is what the binomial draw needs: you cannot
        # find 0.4 of an error in 0.4 of a file.
        expected = float(row.sample_at_full_rate) * multiple
        sampled = int(round(expected))
        if sampled > 0:
            errors = int(rng.binomial(sampled, truth))
            observed = errors / sampled
            # No evidence is not a pass (see the module docstring).
            passes = observed <= target
        else:
            errors = 0
            observed = float("nan")
            passes = False

        run = run + 1 if passes else 0
        met_here = gate is None and run >= hold
        if met_here:
            gate = int(row.week_index)

        rows.append(
            {
                "week_index": int(row.week_index),
                "week_start": row.week_start,
                "period": row.period,
                "automated_items": float(row.automated_items),
                "qa_rate_multiple": multiple,
                "sample_at_full_rate": float(row.sample_at_full_rate),
                "sampled_items": sampled,
                "errors_found": errors,
                "observed_error_rate": observed,
                "at_or_under_target": bool(passes),
                "consecutive_weeks": int(run),
                "gate_met": bool(met_here),
                "qa_rate_lowered": bool(lowered),
            }
        )
    return pd.DataFrame(rows, columns=SERIES_COLUMNS)


def gate_week(automated_plan, assumptions=None):
    """The week the gate is met, as an absolute week index, or None.

    None means the automation never proved itself inside the horizon,
    which is a real answer and not a failure: on a thin sample it is the
    LIKELY answer, and a scenario that silently lowered the rate anyway
    would be reporting a saving nobody earned.
    """
    series = observed_series(automated_plan, assumptions)
    if series.empty:
        return None
    met = series[series["gate_met"]]
    return int(met["week_index"].iloc[0]) if len(met) else None


def gate_plan_week(automated_plan, assumptions=None):
    """The gate week as a PLAN week, which is how a leader says it."""
    assumptions = assumptions or config.load_assumptions()
    gate = gate_week(automated_plan, assumptions)
    if gate is None:
        return None
    return gate - assumptions["calendar"]["history_weeks"] + 1


def qa_multiple_by_week(automated_plan, assumptions=None):
    """{week index: QA rate multiple in force that week}.

    This is the map the hours are built from, and it is the same series
    the report prints, so the two cannot drift apart.
    """
    series = observed_series(automated_plan, assumptions)
    if series.empty:
        return {}
    return {
        int(row.week_index): float(row.qa_rate_multiple)
        for row in series.itertuples()
    }


def sign_off_rate_by_week(automated_plan, assumptions=None):
    """{week index: legal sign-off rate in force that week}.

    Flat at the 5.5 rate unless an input says the legal requirement
    itself changed. Returning a map either way keeps the caller's code
    the same shape whichever answer it is.
    """
    assumptions = assumptions or config.load_assumptions()
    base = float(automation.settings(assumptions)["human_in_the_loop"]["sign_off_rate"])
    series = observed_series(automated_plan, assumptions)
    if series.empty:
        return {}
    if not legal_requirement_changed(assumptions):
        return {int(row.week_index): base for row in series.itertuples()}
    after = after_gate_sign_off_rate(assumptions)
    return {
        int(row.week_index): (after if row.qa_rate_lowered else base)
        for row in series.itertuples()
    }


def hours_freed(series, assumptions=None):
    """QA review hours the lower sample did not have to spend.

    The difference between what each week sampled and what it would have
    sampled at the opening rate, at 5.5's flat review time. Reported
    separately from the plan's own hours because it is the whole point of
    the scenario and should not have to be inferred by subtracting two
    totals.

    Taken off the CONTINUOUS sample (`sample_at_full_rate`), not the
    rounded one, so this figure reconciles exactly with the hours the
    plan was built on. The rounded count is the reviewer's file count and
    exists for the binomial draw; using it here would leave a couple of
    items a week unexplained between the two numbers.
    """
    assumptions = assumptions or config.load_assumptions()
    minutes = float(
        automation.settings(assumptions)["human_in_the_loop"]["qa_review_minutes"]
    )
    if series.empty:
        return {"items_not_sampled": 0.0, "hours": 0.0}
    not_sampled = float(
        (series["sample_at_full_rate"] * (1.0 - series["qa_rate_multiple"])).sum()
    )
    return {
        "items_not_sampled": not_sampled,
        "hours": not_sampled * minutes / 60.0,
    }
