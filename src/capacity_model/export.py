# Coverage Events (spec Section 8, 6.7; task 6c)
#
# Every logged event, with spec 6.7's own field numbers on the headers.
# The numbering is not decoration: F1 to F24 is the schema a real coverage
# log would be built on, and a reader comparing this tab to the spec needs
# to see which field is which without counting columns.
#
# THE COLUMNS ARE READ OFF coverage.py, not restated here. MODEL_FIELDS
# and PERSON_FIELDS already map each field number to its columns, so the
# header is built from that map - a field added to the log appears here
# without an edit, and one renamed cannot drift out of step.
#
# WHO FILLS A FIELD IS ON THE TAB. F13's cause is the model's SUGGESTION,
# and F15, F23 and F24 belong to a person. A log that presented a
# suggested cause as a confirmed one would be the kind of output an
# operation stops trusting after the first argument about a week nobody
# remembers.
# ---------------------------------------------------------------------------

# Which fields a person owns, so the header can say so (spec 6.7).
PERSON_FILLED = "person"
MODEL_SUGGESTS = "F13"


def _event_field_map():
    """column -> (field number, who fills it), from coverage.py's own map."""
    out = {}
    for field, columns, _types, _grain in coverage.MODEL_FIELDS:
        for column in columns:
            out[column] = (field, "model")
    for field, columns in coverage.PERSON_FIELDS:
        for column in columns:
            out[column] = (field, PERSON_FILLED)
    return out


def _event_header(column, field, filled_by):
    """'F10 Hours short before cover', derived rather than restated.

    Built from the column name instead of a second table of labels,
    because a hand-written label table is one more thing that can
    disagree with the log it describes.
    """
    words = column.replace("_", " ")
    label = words[:1].upper() + words[1:]
    if filled_by == PERSON_FILLED:
        return f"{field} {label} (person)"
    if field == MODEL_SUGGESTS:
        return f"{field} {label} (model suggests)"
    return f"{field} {label}"


