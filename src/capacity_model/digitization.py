"""Coordinated digitization: converting records ahead of demand (spec 7).

All data is SYNTHETIC, generated by this model.

THE WFM IDEA
------------
Every other scenario in Section 7 changes how work is handled. This one
changes how much work ARRIVES, permanently, and it is the only lever in
the model with that property.

A chart converted this week is a chart nobody walks to a cabinet for
again - not this year, not next. So the saving is a recurring one bought
with a one-off effort, which is the shape of every backlog-reduction
project worth doing. The question is never "can we do the work" but "how
long until the recurring saving covers the one-off cost", and that is the
break-even week this module reports.

ORDERING, AND WHY IT IS WORTH LESS THAN IT LOOKS
------------------------------------------------
Requests are concentrated. A fifth of the archive draws a much larger
share of the onsite requests - the recently-closed charts, the
long-running cases, the ones a clinic keeps asking about - so converting
MOST-LIKELY-REQUESTED first makes the requested non-digital share fall
faster than the converted share.

    requests removed, converting the first c of the archive:

        c <= a:  (b / a) x c
        c >  a:  b + ((1 - b) / (1 - a)) x (c - a)

Two straight lines: a steep one through the hot records and a shallow one
through the cold tail. The kink at `a` is where the project stops being
obviously worth it and becomes a judgement call.

The first version of this module took a = 20%, b = 80% and called the
resulting 4x the whole finding of the scenario. That was wrong, and the
reason it was wrong is the most useful thing here.

The archive and the concentration are not free inputs. They have to be
consistent with the model's own history, which shows a flat 11% paper
share for 156 weeks while the baseline pulls and digitizes 57,383 paper
charts. Requiring that history to be possible pins N / D, where D is the
request-weighted mean density b^2/a + (1-b)^2/(1-a) (see the calibration
note in assumptions.yaml). And once it is pinned, the project's benefit
goes as (b / a) / D, which runs from 1.00 at no concentration up to only
1.618 at its best.

So concentration is worth at most 1.6x, not 4x. It cuts both ways: it
makes the project's ordering efficient, and it makes REACTIVE conversion
efficient too, which forces the archive bigger to keep the history flat.
The two effects very nearly cancel. An 80-20 archive would have to hold
4.0 million charts to hide the same flat history, against 1.2 million
with no concentration at all, and the project's 160 a week removes
within a factor of 1.6 the same share of requests either way.

CHARTS NOT YET REQUESTED
------------------------
A chart the operation has already pulled is already digital, so the
project cannot convert it (Siri 11/02). The archive the project draws
from is therefore the SURVIVING one: hot and cold tiers each thinned by
the operation's own reactive conversions, which have been running
through the whole history before the project starts.

Each chart sits on paper until its first request, so a tier with request
intensity lambda per chart has a surviving count of

    tier size x exp(-lambda x weeks elapsed)

and the project works down the hot survivors first, then the cold ones.

At the calibrated archive the cap never binds inside the plan year - 160
a week against 367,000 surviving hot charts - and the report says so
rather than leaving it unstated. It does bind before the projected
break-even, at about 1,340 live weeks against 2,036, which is why that
projection is reported as a floor rather than an estimate. At 250,000
charts it would have bound almost at once.

WHAT A CONVERSION SAVES
-----------------------
The record moves from an onsite medium to digital, so three things happen
and the model has to count all three (spec 7, decided 10/28):

    saved    the onsite retrieval (W11) at 25, 35 or 45 minutes
    saved    the reactive digitization (W12) at 15 minutes that W11 drags
             behind it
    ADDED    a digital retrieval (W8) at 10 minutes, because the chart
             still has to be fetched

Reporting only the first two would overstate the saving by the cost of
the work that replaces it, so `savings_report` shows all three and nets
them.
"""

import numpy as np
import pandas as pd

from . import config, supply


def settings(assumptions=None):
    """The digitization block (spec 7). Absent means off."""
    assumptions = assumptions or config.load_assumptions()
    return assumptions.get("scenario", {}).get("digitization", {"enabled": False})


def enabled(assumptions=None):
    """Whether this scenario is switched on.

    Off unless a scenario file says otherwise, and off means the whole
    mechanism below never runs - which is what keeps the baseline's media
    mix the fixed 11% it has always been.
    """
    block = settings(assumptions)
    if not block.get("enabled", False):
        return False
    return items_per_week(assumptions) > 0


def items_per_week(assumptions=None):
    """Network-wide conversions a week: hours x items an hour (spec 7)."""
    block = settings(assumptions)
    return float(block.get("hours_per_week", 0.0)) * float(
        block.get("items_per_hour", 0.0)
    )


def from_week(assumptions=None):
    """The first week the project converts anything.

    The scenario's own starts week, so the weeks before it match the
    baseline exactly - which Section 9 checks.
    """
    assumptions = assumptions or config.load_assumptions()
    scenario = assumptions.get("scenario", {})
    starts = int(scenario.get("starts_week", 1))
    history = int(assumptions["calendar"]["history_weeks"])
    return history + starts - 1


def site_weights(sites=None):
    """Each site's share of the network, by size factor (spec 3.1).

    The same factor that scales a site's request volume scales its paper
    archive, because a site that sees more requests has more records
    behind it. Using anything else here would put the archive in one place
    and the demand for it in another.
    """
    sites = sites or config.load_sites()
    factors = {s["code"]: float(s["size_factor"]) for s in sites["sites"]}
    total = sum(factors.values())
    if total <= 0:
        raise ValueError("site size factors must sum to something positive")
    return {code: factor / total for code, factor in factors.items()}


def archive_by_site(assumptions=None, sites=None):
    """The paper archive, split across sites by size factor (spec 7)."""
    assumptions = assumptions or config.load_assumptions()
    charts = float(settings(assumptions).get("archive_charts", 0.0))
    return {code: charts * weight for code, weight in site_weights(sites).items()}


def concentration(assumptions=None):
    """(hot share of the archive, share of requests it draws) - spec 7.

    Both are calibrated against the model's own history rather than
    chosen; see the calibration note in assumptions.yaml. Read through one
    accessor so the curve, the archive depletion and the drift check can
    never disagree about which pair they are using.
    """
    assumptions = assumptions or config.load_assumptions()
    block = settings(assumptions)
    hot_archive = float(block.get("concentration_archive_share", 0.20))
    hot_requests = float(block.get("concentration_request_share", 0.45))
    if not 0.0 < hot_archive < 1.0:
        raise ValueError(
            f"the concentrated share of the archive must sit between 0 and 1, "
            f"not {hot_archive}"
        )
    if not 0.0 < hot_requests <= 1.0:
        raise ValueError(
            f"the share of requests it draws must sit between 0 and 1, "
            f"not {hot_requests}"
        )
    return hot_archive, hot_requests


def mean_density(assumptions=None):
    """D = b^2/a + (1-b)^2/(1-a): the request-weighted mean density.

    One chart's share of the archive is 1/N; a hot chart's share of the
    REQUESTS is b/(aN). D is the average of that ratio taken over
    requests rather than over charts, so it is 1.0 when demand is spread
    evenly and larger the more concentrated it is.

    It is the quantity the flat history constrains, which is why it is
    worth having a name: the history pins N / D and nothing else.
    """
    hot_archive, hot_requests = concentration(assumptions)
    return (
        hot_requests ** 2 / hot_archive
        + (1.0 - hot_requests) ** 2 / (1.0 - hot_archive)
    )


def reactive_rate(assumptions=None):
    """Onsite retrievals a week, each of which digitizes its chart.

    Measured from the model's own history and recorded in the YAML (spec
    7, 11/02), because the archive is calibrated against it: a rate this
    module assumed for itself could quietly stop matching the history the
    calibration rests on.
    """
    assumptions = assumptions or config.load_assumptions()
    return float(settings(assumptions).get("reactive_conversions_per_week", 0.0))


def drift_budget_points(assumptions=None):
    """Points of paper-share drift a flat history can hide (Siri 11/02)."""
    assumptions = assumptions or config.load_assumptions()
    return float(settings(assumptions).get("history_drift_budget_points", 0.5))


def history_drift_points(assumptions=None, weeks=None, rate=None):
    """How far reactive digitization alone would move the paper share.

    THE CALIBRATION CHECK (spec 7, Section 9, revised 11/02).

    The baseline holds the non-digital share fixed, and that is only
    defensible if the share would barely have moved anyway. This is the
    "barely" put to a number.

    Each chart sits on paper until its FIRST onsite request, which
    digitizes it, so it survives t weeks with probability exp(-lambda t).
    The onsite request rate left after t weeks is the surviving intensity,

        R(t)/R = b exp(-lambda_hot t) + (1-b) exp(-lambda_cold t)

    and the paper share falls in proportion to it. Reactive conversion is
    request-PROPORTIONAL, which is the most aggressive ordering there is -
    a chart is converted because it was requested, so the hot records go
    first without anyone choosing them. That makes this the strictest
    form of the check.

    Returned in POINTS of the paper share, so it compares directly
    against the half-point budget.
    """
    assumptions = assumptions or config.load_assumptions()
    hot_archive, hot_requests = concentration(assumptions)
    charts = float(settings(assumptions).get("archive_charts", 0.0))
    if charts <= 0:
        raise ValueError("the paper archive must hold something")
    if weeks is None:
        weeks = int(assumptions["calendar"]["history_weeks"])
    if rate is None:
        rate = reactive_rate(assumptions)

    lam_hot = hot_requests * rate / (hot_archive * charts)
    lam_cold = (1.0 - hot_requests) * rate / ((1.0 - hot_archive) * charts)
    left = hot_requests * np.exp(-lam_hot * weeks) + (1.0 - hot_requests) * np.exp(
        -lam_cold * weeks
    )
    return non_digital_share(assumptions) * 100.0 * (1.0 - float(left))


def requests_removed_share(converted_fraction, assumptions=None):
    """Share of onsite requests removed, converting most-likely-first.

    The two-line curve in the module note. Vectorised, because the weekly
    walk evaluates it 52 times a site.

    This is the UNCAPPED curve: it assumes every chart in the hot tier is
    still on paper and available to convert. `converted_by_week` applies
    the "not yet requested" cap on top, and the two agree exactly whenever
    that cap does not bind.

    The guarantee worth stating: at a converted fraction of 1.0 this
    returns exactly 1.0, so converting the whole archive removes every
    onsite request and not 1.0000001 of them. The model refuses to remove
    more requests than exist.
    """
    hot_archive, hot_requests = concentration(assumptions)
    c = np.clip(np.asarray(converted_fraction, dtype=float), 0.0, 1.0)
    hot_density = hot_requests / hot_archive
    cold_density = (1.0 - hot_requests) / (1.0 - hot_archive)
    return np.where(
        c <= hot_archive,
        hot_density * c,
        hot_requests + cold_density * (c - hot_archive),
    )


def converted_by_week(assumptions=None, sites=None):
    """The weekly conversion walk, per site (spec 7).

    One row per plan week and site: how many records the project converted
    that week, the cumulative total, the share of the archive that is, and
    the share of onsite REQUESTS it removes.

    Three caps, and each one is a rule rather than a tidy-up:

      the weekly rate, hours x items an hour, split across sites by size
        factor - a site cannot convert faster than the project works;

      the archive itself - a site cannot convert records it does not have,
        so once its archive is exhausted it converts nothing and the
        unused hours are still paid for. That last part matters: the cost
        keeps running after the benefit stops growing;

      the charts NOT YET REQUESTED (Siri 11/02) - a chart the operation
        has already pulled is already digital, so the project cannot
        convert it again. The hot tier is being thinned by the operation's
        own reactive conversions all the while, and has been through the
        whole history, so the project works down the SURVIVORS.

    The requests removed are counted against the ORIGINAL request pool,
    because that is what the flat baseline this is compared against
    assumes. Reactive conversion has in truth already taken some of those
    requests off the table, which means the saving reported here is a
    slight over-statement - about 1.4% inside the plan year, since that is
    a hot chart's chance of being pulled in the weeks that are left.
    Stated rather than corrected, because the baseline keeps its flat
    share by instruction (spec 7, 11/02).
    """
    assumptions = assumptions or config.load_assumptions()
    sites = sites or config.load_sites()

    plan_weeks, mondays = supply.plan_window(assumptions)
    start = from_week(assumptions)
    weights = site_weights(sites)
    archive = archive_by_site(assumptions, sites)
    weekly_total = items_per_week(assumptions)
    hot_archive, hot_requests = concentration(assumptions)
    charts = sum(archive.values())
    rate = reactive_rate(assumptions)

    # Per-chart request intensities. Both scale with site size - a bigger
    # site holds more records AND sees more requests for them - so the
    # ratio is the same everywhere and these are network figures.
    lam_hot = hot_requests * rate / (hot_archive * charts) if charts > 0 else 0.0
    lam_cold = (
        (1.0 - hot_requests) * rate / ((1.0 - hot_archive) * charts)
        if charts > 0
        else 0.0
    )

    rows = []
    project_hot = {code: 0.0 for code in weights}
    project_cold = {code: 0.0 for code in weights}
    for week, monday in zip(plan_weeks, mondays):
        # Weeks the operation has been quietly converting: the whole
        # history, then the plan so far. The project starts on an archive
        # somebody has already been working through.
        elapsed = float(week + 1)
        for code, weight in weights.items():
            held = archive[code]
            hot_tier = hot_archive * held
            cold_tier = held - hot_tier
            # What is left on paper in each tier after reactive conversion.
            hot_left = hot_tier * np.exp(-lam_hot * elapsed)
            cold_left = cold_tier * np.exp(-lam_cold * elapsed)

            hot_room = max(0.0, hot_left - project_hot[code])
            cold_room = max(0.0, cold_left - project_cold[code])
            if week < start:
                converted = 0.0
            else:
                converted = min(weekly_total * weight, hot_room + cold_room)
            # Most-likely-first: the hot survivors go before any cold one.
            take_hot = min(converted, hot_room)
            project_hot[code] += take_hot
            project_cold[code] += converted - take_hot

            cumulative = project_hot[code] + project_cold[code]
            fraction = cumulative / held if held > 0 else 0.0
            # Each tier's conversions carry that tier's share of the
            # requests. With no depletion this reproduces the two-line
            # curve exactly; where the cap bites, it is lower.
            removed = 0.0
            if hot_tier > 0:
                removed += hot_requests * project_hot[code] / hot_tier
            if cold_tier > 0:
                removed += (1.0 - hot_requests) * project_cold[code] / cold_tier
            rows.append(
                {
                    "week_index": week,
                    "week_start": monday,
                    "site": code,
                    "archive_charts": held,
                    "hot_charts_left": hot_left,
                    "converted_this_week": converted,
                    "converted_cumulative": cumulative,
                    "converted_hot": project_hot[code],
                    "converted_cold": project_cold[code],
                    "converted_fraction": fraction,
                    "requests_removed_share": min(1.0, removed),
                    # True once the project has run out of hot survivors
                    # and is into the cold tail, where a converted chart
                    # is worth a fraction of what the first ones were.
                    "cap_binds": project_cold[code] > 0.0,
                }
            )
    return pd.DataFrame(rows)


def live_weeks_of_hot_charts(assumptions=None, sites=None, horizon=5000):
    """How many live weeks before the project runs out of HOT paper charts.

    The straight-line projection in the break-even report only holds
    while every chart the project converts carries the same high request
    probability - that is, while there are hot charts still on paper. Past
    that point a converted chart is worth a fraction of what the first
    ones were and the saving stops growing at the same rate.

    The hot tier drains from both ends: the operation keeps pulling
    charts out of it reactively whether the project exists or not, and
    the project converts from what is left. So this is the first live
    week w where

        hot tier x exp(-lambda_hot x (weeks elapsed)) - rate x w  <=  0

    Returned so the report can say whether its own projection stays
    inside its own assumption, rather than quietly stepping outside it.
    """
    assumptions = assumptions or config.load_assumptions()
    sites = sites or config.load_sites()
    hot_archive, hot_requests = concentration(assumptions)
    charts = sum(archive_by_site(assumptions, sites).values())
    per_week = items_per_week(assumptions)
    if charts <= 0 or per_week <= 0:
        return float("inf")

    hot_tier = hot_archive * charts
    lam_hot = hot_requests * reactive_rate(assumptions) / hot_tier
    start = from_week(assumptions)
    for w in range(1, horizon + 1):
        left = hot_tier * np.exp(-lam_hot * (start + w)) - per_week * w
        if left <= 0:
            return float(w)
    return float(horizon)


def onsite_factor_by_week(assumptions=None, sites=None, table=None):
    """{(week, site): what is LEFT of the onsite request share}.

    One minus the requests removed. This is the multiplier the work-volume
    build puts on the onsite media shares, and the share it takes off them
    moves to digital - the record still exists and still gets fetched, it
    is just not in a cabinet any more.
    """
    if table is None:
        table = converted_by_week(assumptions, sites)
    return {
        (row.week_index, row.site): 1.0 - row.requests_removed_share
        for row in table.itertuples()
    }


def weekly_cost(assumptions=None):
    """What the added hours cost a week (spec 7, decided 10/28).

    Paid hours at the project role's hourly rate. NOT a productive-hour
    rate: these are hours bought and paid for, and the shrinkage that
    makes a productive hour cost more is already inside the rate the
    retrieval queue is charged. Loading it twice would make the project
    look worse than it is.
    """
    assumptions = assumptions or config.load_assumptions()
    block = settings(assumptions)
    role = block.get("project_role", "records_specialist")
    hourly = float(supply.role_settings(role, assumptions)["hourly_cost"])
    return float(block.get("hours_per_week", 0.0)) * hourly


def non_digital_share(assumptions=None):
    """The baseline's onsite share of charts: paper + microfiche + archive.

    Read from the record_media table rather than restated, so this can
    never disagree with the mix the work volume is built from.
    """
    assumptions = assumptions or config.load_assumptions()
    return sum(
        float(m["share"]) for m in assumptions["record_media"] if m.get("onsite")
    )


def onsite_media(assumptions=None):
    """The media codes a Records Specialist has to walk to a cabinet for."""
    assumptions = assumptions or config.load_assumptions()
    return [m["code"] for m in assumptions["record_media"] if m.get("onsite")]


def digital_media(assumptions=None):
    """Where a converted record lands: the client system (spec Section 1)."""
    assumptions = assumptions or config.load_assumptions()
    for medium in assumptions["record_media"]:
        if not medium.get("onsite") and medium["code"] == "digital":
            return medium["code"]
    raise ValueError("no digital medium found in record_media")
