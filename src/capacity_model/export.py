def digitization_backlog_table(run, assumptions=None):
    """The W12 digitization queue per plan week, network-wide (spec 4.4).

    Days of inventory is rebuilt from the network totals rather than
    averaged across the six sites' own figures: inventory is a ratio, and
    the mean of six ratios is not the ratio of the sums.
    """
    assumptions = assumptions or config.load_assumptions()
    queues = run["queues"]
    rows = queues[queues["work_type"] == DIGITIZATION_WORK_TYPE]
    if not len(rows):
        return pd.DataFrame(
            columns=[source for _h, source, _f, _w, _t
                     in DIGITIZATION_BACKLOG_COLUMNS]
        )
    grouped = rows.groupby(["week_index", "week_start"], as_index=False).agg(
        arrivals=("arrivals", "sum"),
        ending_backlog=("ending_backlog", "sum"),
        goal_business_days=("goal_business_days", "max"),
    )
    # Same arithmetic backlog.py uses, on the network totals: open items
    # over the DAILY arrival rate. A week with no arrivals has no
    # meaningful days of inventory, so it is left blank rather than
    # divided by zero.
    days = float(assumptions["calendar"]["business_days_per_week"])
    grouped["days_of_inventory"] = [
        backlog / (arrivals / days) if arrivals > 0 else float("nan")
        for backlog, arrivals in zip(
            grouped["ending_backlog"], grouped["arrivals"]
        )
    ]
    grouped["goal_met"] = (
        grouped["days_of_inventory"] <= grouped["goal_business_days"] + 1e-12
    )
    grouped["plan_week"] = [
        plan_week(week, assumptions) for week in grouped["week_index"]
    ]
    grouped["week_start"] = grouped["week_start"].astype(str).str[:10]
    return grouped.sort_values("plan_week").reset_index(drop=True)


