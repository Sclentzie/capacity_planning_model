def _reference(measure, row):
    """A live reference into Capacity Scenarios, quoted for the space."""
    letter = SCENARIO_LETTERS[measure]
    return f"='{SCENARIOS_TAB}'!{letter}{row}"


def write_summary(sheet, rows, assumptions):
    """The curated headline block (spec Section 8, decided 11/03).

    `rows` is what Capacity Scenarios wrote, in its order, so the row
    numbers the references point at come from the same object that put the
    values there.
    """
    identity = assumptions["meta"]
    calendar = assumptions["calendar"]
    row_of = {
        name: SCENARIO_FIRST_DATA_ROW + offset
        for offset, name in enumerate(rows["scenario"])
    }
    missing = [name for name, _finding in HEADLINES if name not in row_of]
    if missing:
        raise ValueError(f"Summary headlines name scenarios that did not run: {missing}")

    # "- SYNTHETIC" in capitals, like every other tab, even though
    # meta.model_name already says "(synthetic)". The label is the thing a
    # reader scans for and a lowercase word inside a long title is not it.
    _put(
        sheet, "A1", f"{identity['model_name']} - Summary - SYNTHETIC", TITLE_FONT
    )
    _put(sheet, "A2", SYNTHETIC, NOTE_FONT)
    _put(
        sheet,
        "A3",
        f"Plan year: {calendar['plan_weeks']} weeks from "
        f"{calendar['plan_start']}, on {calendar['history_weeks']} weeks of "
        f"generated history from {calendar['history_start']}.",
        NOTE_FONT,
    )

    # --- the baseline, which everything below is measured against -------
    row = 5
    _put(sheet, f"A{row}", "THE BASELINE PLAN", SECTION_FONT)
    row += 1
    baseline_row = row_of["Baseline"]
    for label, measure, number_format in SUMMARY_MEASURES:
        _put(sheet, f"A{row}", label, BODY_FONT)
        cell = _put(
            sheet, f"B{row}", _reference(measure, baseline_row), BODY_BOLD,
            number_format,
        )
        cell.border = UNDERLINE
        sheet[f"A{row}"].border = UNDERLINE
        row += 1

    # --- the eight a leader would act on --------------------------------
    row += 1
    _put(sheet, f"A{row}", "WHAT A LEADER WOULD ACT ON", SECTION_FONT)
    row += 1
    header_row = row
    for index, (header, _measure, width) in enumerate(
        SUMMARY_HEADLINE_COLUMNS, start=1
    ):
        letter = get_column_letter(index)
        cell = _put(sheet, f"{letter}{row}", header, HEADER_FONT, alignment=HEADER_ALIGN)
        cell.fill = HEADER_FILL
        sheet.column_dimensions[letter].width = width
    sheet.row_dimensions[header_row].height = 30
    row += 1

    for name, finding in HEADLINES:
        source = row_of[name]
        _put(sheet, f"A{row}", name, BODY_BOLD).border = UNDERLINE
        for index, (_header, measure, _width) in enumerate(
            SUMMARY_HEADLINE_COLUMNS[1:-1], start=2
        ):
            letter = get_column_letter(index)
            number_format = dict(
                (header, fmt)
                for header, _s, fmt, _w in SCENARIO_COLUMNS
            )[measure]
            cell = _put(
                sheet, f"{letter}{row}", _reference(measure, source), BODY_FONT,
                number_format,
            )
            cell.border = UNDERLINE
        last = get_column_letter(len(SUMMARY_HEADLINE_COLUMNS))
        cell = _put(sheet, f"{last}{row}", finding, BODY_FONT, alignment=WRAP_TOP)
        cell.border = UNDERLINE
        sheet.row_dimensions[row].height = _wrapped_height(
            finding, SUMMARY_HEADLINE_COLUMNS[-1][2]
        )
        row += 1

    # --- the notes a reader needs before quoting any of it --------------
    row += 1
    _put(sheet, f"A{row}", "HOW TO READ THIS", SECTION_FONT)
    row += 1
    # The notes sit in column A and run under the whole block, so they
    # wrap against the full table width rather than column A's own.
    note_width = sum(width for _h, _m, width in SUMMARY_HEADLINE_COLUMNS)
    for note in summary_notes(assumptions, len(rows)):
        _put(sheet, f"A{row}", note, NOTE_FONT, alignment=WRAP_TOP)
        sheet.row_dimensions[row].height = _wrapped_height(note, note_width, 12.0)
        row += 1

    sheet.freeze_panes = "A5"
    return row


def summary_notes(assumptions=None, scenario_count=None):
    """The four things a reader has to know before quoting a number.

    Kept as a function rather than a block of literals in the writer
    because the tie-out test reads them: a note that silently stopped
    being written would be the easiest thing in this module to lose.
    """
    assumptions = assumptions or config.load_assumptions()
    goal = assumptions["backlog"]["overall_turnaround_goal_days"]
    # Counted, never written in: a note that says "13 more runs" is a
    # number in the logic, and it goes stale the first time a scenario is
    # added. Falls back to the scenario folder when no count is passed.
    if scenario_count is None:
        scenario_count = len(scenarios.list_scenarios(assumptions))
    others = int(scenario_count) - len(HEADLINES)
    return (
        "SYNTHETIC DATA. Northbrook Records Services is a fictional "
        "operation and every figure here is generated by this model from a "
        "fixed random seed. Nothing in this workbook comes from a real "
        "company, patient or employee.",
        "ALL-IN COST = labour + machine. Labour is spec 6.4: regular pay "
        "for everybody on the payroll, including people still in training, "
        "plus overtime. Machine is the automation's own invoice: the "
        "per-item fee, the setup spread over a year, and one shared "
        "platform fee. Quoting labour alone credits an automation scenario "
        "with its saving and none of its cost - on these volumes the two "
        "are the same order of magnitude.",
        f"TURNAROUND is the requester's view: every request counted once, "
        f"automated items at the machine's own completion time, against "
        f"the {goal}-business-day goal. A weekly model cannot see "
        f"within-day aging, so this is days of inventory rather than true "
        f"response time.",
        "THE ROSTER IS HELD in every scenario. None of them re-hires for "
        "its own change, so each one reports what the change costs the "
        "operation it has - which is why a saving in required hours is "
        "only a saving in money where it cancels an overtime hour or a "
        "hiring class.",
        f"ALL {len(HEADLINES)} HEADLINES ABOVE, AND {others} MORE RUNS, "
        f"are on the '{SCENARIOS_TAB}' tab with every measure and every "
        f"difference against the baseline.",
    )


