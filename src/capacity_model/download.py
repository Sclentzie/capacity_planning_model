"""The Excel file a reader downloads from the dashboard (Siri, 11/23).

All data is SYNTHETIC, generated by this model.

THE WFM IDEA
------------
A dashboard is read in a meeting and a spreadsheet is what leaves it.
Until now the only thing that left this page was a CSV: correct, complete
and completely unformatted, so the first thing anyone did with it was
spend ten minutes making it readable - widening columns, adding dollar
signs, bolding a header row - and the file that then got forwarded was
nobody's version of the model.

So the main download is now the workbook's own styling wrapped around
exactly what is on screen, and the CSV stays beside it as the raw-data
option for anyone who wants to do arithmetic on it.

WHY THIS IS NOT A SECOND EXPORTER
---------------------------------
Every cell here is written by `export`: the same column specs, the same
number formats, the same header fill, the same auto-fit, the same live
formulas. This module chooses WHICH rows and writes the few lines of
context a download needs that a workbook tab does not - which run, which
filters, and for a custom run, what was changed. If the workbook's
styling moves, this moves with it, because there is nothing here to move
separately.

WHAT "EXACTLY WHAT IS ON SCREEN" MEANS
--------------------------------------
The same rows, in the same order, under the same headers. Not the same
ROUNDING: the screen rounds to what a number format prints and the file
carries the figure, exactly as the CSV has since 7b, because a
spreadsheet is a thing people sum.
"""

import io

from openpyxl import Workbook
from openpyxl.utils import get_column_letter

from . import api, export, views

# What a browser needs to be told it is receiving.
EXCEL_MIME = (
    "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
)

# WHAT THE TWO BUTTONS SAY. Here rather than on the page, because a test
# that typed the labels again would pass while the page said something
# else - and because "formatted" and "raw data" is the whole distinction
# between them, not decoration on it.
EXCEL_LABEL = "Download Excel (formatted)"
CSV_LABEL = "Download CSV (raw data)"

PLAN_SHEET = "Capacity Plan"
SCENARIOS_SHEET = "Capacity Scenarios"

# The comparison table's first column, named where the measures are named
# rather than spelled again here.
SCENARIO_HEADER = api.COMPARISON_MEASURES[0][0]


def _book():
    """An empty workbook with openpyxl's default sheet removed."""
    book = Workbook()
    book.remove(book.active)
    return book


def _preamble(sheet, title, lines, changes=None):
    """Title, the SYNTHETIC label, the context lines, and what changed.

    Returns the row the header should go on. The heading itself is
    written by `export`, so this file is labelled the way every tab is.

    WHY THE CONTEXT IS ABOVE THE DATA and not in a note at the bottom: a
    downloaded file is opened cold, often by somebody who was not in the
    meeting, and "which run is this, and what was filtered out" is the
    first question. The data block starts one row below, so a reader's
    first scroll still lands on the figures.
    """
    row = export.write_heading(sheet, title, lines)

    if changes is not None:
        # A CUSTOM RUN'S INPUTS EXIST NOWHERE ELSE. The 21 saved runs are
        # described in the workbook and in the spec; a run somebody built
        # in the panel is described only by what they typed, so a file
        # that did not carry it would be unreadable a week later. Same
        # rule the custom CSV has followed since 7c, written as a section
        # rather than as comment lines because a spreadsheet has no
        # comment character.
        row += 1
        export.write_line(sheet, row, "INPUTS CHANGED", export.SECTION_FONT)
        row += 1
        for line in changes or [
            "Nothing changed: these are the baseline inputs."
        ]:
            export.write_line(sheet, row, line)
            row += 1

    return row + 1


def sourced_by_header(columns):
    """The workbook's own column spec, re-sourced by header.

    The workbook builds its tables from the model's frames, whose columns
    are named `required_hours`; the page builds the same table under the
    workbook's own HEADERS, because that is what a reader sees and what
    the CSV has carried since 7b. Same columns, same formats, same
    widths, same total flags - only the lookup changes, so a column added
    to the tab arrives here without anybody remembering to add it.

    A source of None stays None: those are the live formulas, and they
    are still live here.
    """
    return tuple(
        (header, None if source is None else header, number_format, width, total)
        for header, source, number_format, width, total in columns
    )


PLAN_COLUMNS = sourced_by_header(export.CAPACITY_PLAN_COLUMNS)


def plan_book(view, *, run_name, filters=(), changes=None):
    """The filtered Capacity Plan rows, styled as the workbook styles them.

    `view` is exactly what the page is showing (views.plan_view, already
    filtered), `filters` the plain lines saying what was filtered, and
    `changes` the inputs a custom run changed - None for a saved run,
    which needs no such section because the workbook already describes
    it.
    """
    book = _book()
    sheet = book.create_sheet(title=PLAN_SHEET)

    lines = [
        f"{run_name}, plan year, {len(view):,} rows, exactly as the "
        f"dashboard is showing them. Every measure is written by the "
        f"model; the hours gap and the total row are live Excel formulas "
        f"over those values.",
    ]
    lines.extend(filters)
    lines.append(
        "Figures are at full precision, not the rounded ones on screen. "
        "Roles are named as a person would say them; the CSV download "
        "keeps the model's own codes, so a downloaded row can be matched "
        "to a workbook row."
    )
    header_row = _preamble(sheet, PLAN_SHEET, lines, changes=changes)

    headers = [header for header, *_rest in PLAN_COLUMNS]
    required = _letter(headers, "Required hours")
    available = _letter(headers, "Available hours")

    def formula(header, row):
        if header == views.HOURS_GAP_HEADER:
            return f"={available}{row}-{required}{row}"
        return None

    placed = export.write_detail_tab(
        sheet, PLAN_SHEET, PLAN_COLUMNS, view, export.CAPACITY_PLAN_NOTES,
        formula=formula, total_label="TOTAL OF THESE ROWS (flows only)",
        start_row=header_row,
    )
    # Frozen below the header and right of the four columns that say
    # which row this is, as the tab freezes them.
    sheet.freeze_panes = f"E{placed['first']}"
    return book


def _letter(headers, header):
    """Which column letter a header landed in, for a formula to point at."""
    return get_column_letter(headers.index(header) + 1)


# The comparison table is the one view with no workbook tab behind it in
# this shape: the Capacity Scenarios tab is alphabetical and carries
# seventeen columns of its own, while the page ranks the runs by what
# they do to the all-in cost and shows the kind beside the name. The
# download follows the SCREEN, because that is what was asked for - so
# the columns are taken from the table itself and the formats, widths and
# styling from the tab.
KIND_WIDTH = 13
DEFAULT_WIDTH = 15


def comparison_columns(table):
    """A column spec for whatever the comparison table is showing."""
    widths = {
        header: width
        for header, _source, _format, width in export.SCENARIO_COLUMNS
    }
    columns = []
    for header in table.columns:
        if header == views.DIFFERENCE_HEADER:
            # Kept LIVE, like every difference in the workbook: a reader
            # sees the subtraction against the baseline row rather than
            # being asked to trust it.
            source = None
        else:
            source = header
        columns.append(
            (
                header,
                source,
                views.SCENARIO_FORMATS.get(header),
                widths.get(header, KIND_WIDTH if header == views.KIND_HEADER
                           else DEFAULT_WIDTH),
                False,
            )
        )
    return tuple(columns)


COMPARISON_NOTES = (
    "RANKED, NOT ALPHABETICAL, and that is the difference between this "
    "and the workbook's Capacity Scenarios tab. The tab is a reference "
    "table and ranking one smuggles in an opinion; this file is the "
    "answer to 'which runs save money', so the biggest saving is the "
    "first row.",
    "KIND IS DECLARED BY THE RUN, not worked out here. A CHOICE is "
    "something the operation could decide to do, a RISK is something "
    "that could happen to it which nobody is proposing, and a "
    "SENSITIVITY varies one input of another run to test whether its "
    "finding holds. The ranking puts all three next to each other, and "
    "the cheapest row is not always something anyone is offering to do.",
    "THE DIFFERENCE COLUMN IS A LIVE FORMULA against the Baseline row, "
    "so a reader can see the subtraction. Every other figure is written "
    "by the model, which is what lets the workbook be tied to it to the "
    "cent.",
    "NO TOTAL ROW. These are twenty-one answers to the same question, "
    "not twenty-one parts of one answer, and adding them would produce a "
    "number with no meaning.",
)


def comparison_book(table):
    """Every run, ranked, as the Compare-all view is showing them."""
    book = _book()
    sheet = book.create_sheet(title=SCENARIOS_SHEET)

    columns = comparison_columns(table)
    header_row = _preamble(
        sheet,
        SCENARIOS_SHEET,
        [
            f"All {len(table)} runs, ranked by what each does to the all-in "
            f"cost against the Baseline, exactly as the dashboard is "
            f"showing them.",
            "Costs are stored to the cent and shown to the dollar. "
            "Turnaround is the requester's view.",
        ],
    )

    headers = [header for header, *_rest in columns]
    all_in = _letter(headers, views.ALL_IN_HEADER)
    names = list(table[SCENARIO_HEADER])
    baseline_row = header_row + 1 + names.index(views.BASELINE_LABEL)

    def formula(header, row):
        if header == views.DIFFERENCE_HEADER:
            return f"={all_in}{row}-{all_in}${baseline_row}"
        return None

    placed = export.write_detail_tab(
        sheet, SCENARIOS_SHEET, columns, table, COMPARISON_NOTES,
        formula=formula, start_row=header_row,
    )
    sheet.freeze_panes = f"B{placed['first']}"
    return book


def excel_bytes(book):
    """The workbook as bytes, for st.download_button."""
    buffer = io.BytesIO()
    book.save(buffer)
    return buffer.getvalue()


