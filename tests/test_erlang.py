def test_walk_in_goal_comes_from_the_assumptions(live_queues):
    """Spec 4.1 and Section 1: 90% of walk-ins served within 10 minutes."""
    walk_ins = next(g for g in live_queues["goals"] if g["code"] == "walk_ins")
    assert walk_ins["service_level"] == 0.90
    assert walk_ins["target_seconds"] == 600
    assert walk_ins["work_type"] == "W19"


def test_walk_in_counter_reference_case(live_queues):
    """A busy counter: 12 walk-ins in a half-hour at an 8-minute handle time.

    Arrivals are illustrative - erlang.py is not wired to the work-volume
    data until the next task - but the goal, the cap and the interval all
    come from assumptions.yaml.

    A = 12 x 480 / 1800 = 3.2 Erlangs, and five people clear 90% within ten
    minutes at 64% occupancy. Note how much gentler a ten-minute target is
    than a twenty-second one: the same traffic on the phones would need
    noticeably more people.
    """
    walk_ins = next(g for g in live_queues["goals"] if g["code"] == "walk_ins")
    handle_time = 8 * 60  # spec Section 1, W19

    staff, offered, level, busy = erlang.staff_for_interval(
        arrivals=12,
        handle_time_seconds=handle_time,
        interval_seconds=live_queues["interval_seconds"],
        target_seconds=walk_ins["target_seconds"],
        service_level_goal=walk_ins["service_level"],
        occupancy_cap=live_queues["occupancy_cap"],
    )

    assert offered == pytest.approx(3.2)
    assert staff == 5
    assert level == pytest.approx(0.969586, abs=1e-6)
    assert busy == pytest.approx(0.64)
    assert erlang.service_level(4, offered, 600, handle_time) < walk_ins["service_level"]


def test_a_quiet_counter_still_needs_someone_there(live_queues):
    """Two walk-ins an hour is 0.53 Erlangs - and still needs a person.

    Erlang C never rounds a live queue down to nobody: somebody has to be at
    the counter when a requester walks in, however rarely that happens. This
    is why the onsite priority rule in spec 4.5 protects live work first.
    """
    walk_ins = next(g for g in live_queues["goals"] if g["code"] == "walk_ins")
    staff, offered, level, _busy = erlang.staff_for_interval(
        arrivals=2,
        handle_time_seconds=8 * 60,
        interval_seconds=live_queues["interval_seconds"],
        target_seconds=walk_ins["target_seconds"],
        service_level_goal=walk_ins["service_level"],
        occupancy_cap=live_queues["occupancy_cap"],
    )
    assert offered == pytest.approx(0.533333, abs=1e-6)
    assert staff >= 1
    assert level >= walk_ins["service_level"]


