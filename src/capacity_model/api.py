def all_results(baseline=None, sites=None, paths=None):
    """Every scenario in scenarios/, run and shaped (spec 7, Section 8).

    Calls scenarios.run, which is the same function the workbook export
    runs on, so the saved results and the workbook are the same numbers
    from the same pass rather than two runs that ought to agree.
    """
    baseline = baseline or config.load_assumptions()
    sites = sites if sites is not None else config.load_sites()
    result = scenarios.run(paths, baseline, sites)
    return {
        "comparison": result["comparison"],
        "scenarios": {
            key: results(built, key=key) for key, built in result["runs"].items()
        },
    }


def comparison_view(comparison):
    """The comparison table under the workbook's own column headers."""
    columns = {header: comparison[key] for header, key in COMPARISON_MEASURES}
    return pd.DataFrame(columns)


def inputs_fingerprint():
    """A hash per input file, so a stale saved result can be spotted.

    Cheap, and it catches the ordinary case: somebody changed an
    assumption and did not rebuild. It cannot catch a changed FORMULA,
    which is why the test that recomputes every cell exists as well.
    """
    marks = {}
    for name in INPUT_FILES:
        text = (config.REPO_ROOT / name).read_bytes()
        marks[name] = hashlib.sha256(text).hexdigest()
    digest = hashlib.sha256()
    for path in sorted(scenarios.scenario_dir().glob("*.yaml")):
        digest.update(path.name.encode("utf-8"))
        digest.update(path.read_bytes())
    marks["scenarios"] = digest.hexdigest()
    return marks


def _plain(value):
    """One cell, as a type JSON can hold without losing anything.

    Floats go through Python's shortest round-trip repr, so a figure that
    ties to the cent still ties to the cent after a save and a load.
    """
    if value is None:
        return None
    if isinstance(value, str):
        return value
    if hasattr(value, "item"):          # numpy scalar -> python scalar
        value = value.item()
    if isinstance(value, bool) or isinstance(value, (int, float)):
        return value
    return str(value)                   # dates and anything else, as text


def _frame_payload(frame):
    """A frame as columns plus rows, which gzips far smaller than records."""
    return {
        "columns": [str(column) for column in frame.columns],
        "data": [
            [_plain(cell) for cell in row]
            for row in frame.itertuples(index=False, name=None)
        ],
    }


def _restore_frame(payload):
    """Rows and columns back into a frame, with the numbers numeric again.

    Built from a list of rows, so pandas can hand back object columns that
    merely contain numbers. infer_objects puts the dtypes back - the
    dashboard formats a money column as money only if it is numeric, and
    a comparison against a fresh run should not turn on how a number was
    stored.
    """
    frame = pd.DataFrame(payload["data"], columns=payload["columns"])
    return frame.infer_objects()


def payload(bundle, assumptions=None):
    """The whole saved file as plain data, ready to be written."""
    assumptions = assumptions or config.load_assumptions()
    scenario_payloads = {}
    for key, result in bundle["scenarios"].items():
        scenario_payloads[key] = {
            "key": result["key"],
            "name": result["name"],
            "starts_week": result["starts_week"],
            "what_it_changes": result["what_it_changes"],
            "kind": result["kind"],
            "summary": {
                name: _plain(value) for name, value in result["summary"].items()
            },
            "machine_spend": {
                name: _plain(value)
                for name, value in result["machine_spend"].items()
            },
            "tables": {
                name: _frame_payload(result[name]) for name in DETAIL_TABLES
            },
        }
    return {
        "meta": {
            "synthetic": True,
            "label": SYNTHETIC_LABEL,
            "spec": "docs/Capacity_Model_Spec.md",
            "built_by": f"{__name__}.save_results",
            "scenario_count": len(scenario_payloads),
            "plan_weeks": int(assumptions["calendar"]["plan_weeks"]),
            "detail_tables": list(DETAIL_TABLES),
            "inputs": inputs_fingerprint(),
        },
        "comparison": _frame_payload(bundle["comparison"]),
        "scenarios": scenario_payloads,
    }


def results_path(assumptions=None):
    assumptions = assumptions or config.load_assumptions()
    paths = assumptions["paths"]
    return config.resolve_path(paths["app_data_dir"], paths["scenario_results_json"])


def save_results(bundle=None, assumptions=None, sites=None, path=None):
    """Run every scenario and write the one file the dashboard loads.

    `path` is here so a test can write somewhere else: a test that wrote
    the committed file would change the repository as a side effect of
    checking it.
    """
    assumptions = assumptions or config.load_assumptions()
    bundle = bundle if bundle is not None else all_results(assumptions, sites)
    path = path or results_path(assumptions)
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(payload(bundle, assumptions), separators=(",", ":"))
    # Two things are stripped out of the gzip header so that the same
    # numbers always produce the same bytes:
    #
    #   mtime=0     a wall-clock stamp would make every rebuild look like a
    #               change in git even when not one figure moved.
    #   filename="" gzip otherwise records the file's OWN name in the
    #               header, so the bytes depended on what the file was
    #               called - which is what caught this.
    #
    # A fixed-seed model whose saved output is not byte-stable is a model
    # whose output nobody can diff.
    with open(path, "wb") as raw:
        with gzip.GzipFile(
            fileobj=raw, mode="wb", compresslevel=9, mtime=0, filename=""
        ) as handle:
            handle.write(body.encode("utf-8"))
    return path


def load_results(path=None, assumptions=None):
    """The saved results, with the frames back as frames.

    This is what the dashboard calls. It reads a file and nothing else -
    no model run, no YAML - so a hosted app starts in under a second.
    """
    path = path or results_path(assumptions)
    with gzip.open(path, "rb") as handle:
        raw = json.loads(handle.read().decode("utf-8"))
    scenario_results = {}
    for key, saved in raw["scenarios"].items():
        shaped = {
            name: saved[name]
            for name in ("key", "name", "starts_week", "what_it_changes", "kind")
        }
        shaped["summary"] = saved["summary"]
        shaped["machine_spend"] = saved["machine_spend"]
        for name, table in saved["tables"].items():
            shaped[name] = _restore_frame(table)
        scenario_results[key] = shaped
    return {
        "meta": raw["meta"],
        "comparison": _restore_frame(raw["comparison"]),
        "scenarios": scenario_results,
    }


def main():
    baseline, sites, _skills = config.load_all()
    paths = scenarios.list_scenarios(baseline)
    print(
        f"Saved results for the dashboard (spec Section 8): "
        f"{len(paths)} runs, all SYNTHETIC"
    )

    started = time.time()
    bundle = all_results(baseline, sites, paths)
    ran = time.time() - started
    written = save_results(bundle, baseline, sites)
    size = written.stat().st_size

    print(f"  ran {len(bundle['scenarios'])} scenarios in {ran / 60:.1f} minutes")
    print(f"  results -> {written}")
    print(f"  {size:,} bytes ({size / 1024:.0f} KB)")

    loaded = load_results(written, baseline)
    print(f"  loads back as {len(loaded['scenarios'])} scenarios")
    table = comparison_view(loaded["comparison"])
    print()
    print(table.to_string(index=False, float_format=lambda v: f"{v:,.2f}"))


if __name__ == "__main__":
    main()
