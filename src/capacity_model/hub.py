"""Central records hub: one pooled records team (spec Section 7).

All data is SYNTHETIC, generated by this model.

THE WFM IDEA
------------
This is the second pooling scenario in Section 7, and it is worth reading
next to the first one, because they pool different things and only one of
them gets something for nothing.

Centralized phones wins through ERLANG. One large random queue needs
proportionally less spare capacity than six small ones, because the
randomness averages out. That gain is real and it is free, because a
telephone call does not have to travel to the person who answers it.

A records hub cannot win that way. Retrieval is BACKLOG work, not a live
queue, and backlog work has no Erlang penalty to pool away: a hundred
hours of chart pulls is a hundred hours whether it sits at one site or
six. Pooling the randomness of a backlog buys nothing, because a backlog
is allowed to wait - that is what the inventory target in 4.3 is for.

What a hub buys is STRUCTURAL rather than statistical, and measuring it
(11/02) turned up something the spec's own framing gets wrong.

The expected answer was the FLOOR: spec Section 1 keeps 2 Records
Specialists at every site so a site is never without records cover, and
six sites at a floor of 2 is twelve people whether the work justifies
twelve or not. But sized against this model's volumes, the floor barely
binds - every site needs about 2.2 to 2.8 Records Specialists anyway, and
only the smallest (S2, at 1.90) is held up by it. The floor is worth
0.097 FTE across the whole network.

What the hub actually buys is ROUNDING. Each site rounds its own
fractional requirement up to a whole person, and six sites round up six
times: 14.254 FTE of work becomes 17 people. One hub rounds once, and the
same work becomes 15. That is 2 people, and 2.649 of the 2.746 FTE of
slack recovered.

The distinction matters, because it tells you when a hub is worth
considering: not when sites are small enough to hit the floor, but when
the per-site requirement has a large fractional part. It also means the
saving does not scale with the network - pooling six teams recovers
about half a person per site once, and pooling twelve would recover the
same half each, no more.

WHAT IT PAYS FOR IT
-------------------
Two costs, and the scenario exists to put numbers on both:

    DELIVERY. A chart pulled at the hub for another site has to get
      there - 1 business day inside a cluster, 2 between. Added to the
      turnaround of every hub-retrieved item, so the service cost of
      pooling is visible instead of assumed away.

    COUNTER HELP. Spec 4.5 gives half of a Records Specialist's spare
      hours to their own site's counter, spread across the day. Take the
      Records Specialists out of five sites and that help leaves with
      them, so Onsite Associates have to cover what it was covering. This
      is the cost most likely to be missed in a real business case,
      because it lands on a different role's budget line.

NOT MODELLED
------------
The one-time cost of physically moving the archive to the hub: boxes,
trucks, re-indexing, and the service running at two addresses while it
happens. So every figure here is an UPPER BOUND on the hub's case, and
the report says so rather than leaving a reader to assume it was counted.
"""

import numpy as np
import pandas as pd

from . import config


def settings(assumptions=None):
    """The records_hub block (spec 7). Absent means off."""
    assumptions = assumptions or config.load_assumptions()
    return assumptions.get("scenario", {}).get("records_hub", {"enabled": False})


def enabled(assumptions=None):
    """Whether this scenario is switched on.

    Off unless a scenario file says so, and off means every function below
    is never reached - which is what keeps the baseline's six per-site
    records teams exactly as they were.
    """
    return bool(settings(assumptions).get("enabled", False))


def moved_work_types(assumptions=None):
    """The work types the hub team does instead of the sites (spec 7)."""
    return list(settings(assumptions).get("moved_work_types", []))


def delivery_work_types(assumptions=None):
    """The moved types whose items physically travel (spec 7, 11/02)."""
    return list(settings(assumptions).get("delivery_work_types", []))


def cluster_of(sites=None):
    """{site code: cluster code}, from sites.yaml."""
    sites = sites or config.load_sites()
    return {s["code"]: s["cluster"] for s in sites["sites"]}


def delivery_days(hub, site, assumptions=None, sites=None):
    """Business days for an item retrieved at `hub` to reach `site`.

    Zero at the hub itself - the record is already in the building, and
    that zero is exactly why the hub choice is volume-weighted: putting
    the hub at the busiest site takes the largest single weight to nothing.
    """
    assumptions = assumptions or config.load_assumptions()
    block = settings(assumptions)
    if hub == site:
        return 0.0
    clusters = cluster_of(sites)
    if hub not in clusters or site not in clusters:
        raise ValueError(f"unknown site in the delivery pair ({hub}, {site})")
    if clusters[hub] == clusters[site]:
        return float(block.get("delivery_days_within_cluster", 1))
    return float(block.get("delivery_days_between_clusters", 2))


def volume_by_site(sites=None):
    """Each site's share of network volume, by size factor (spec 3.1).

    The hub has to be chosen before the work table exists, because the
    choice decides where the Records Specialists SIT and that is needed
    to build the roster that the work is then planned against. So the
    weight is the size factor, which is the model's own definition of
    relative site volume - sites.yaml states it multiplies the base
    requests per week - and it costs nothing to evaluate.

    It is not quite the realised volume, because the forecast carries a
    little per-site drift. `volume_by_site_from_work` measures the real
    thing and the report checks the two pick the same hub; a Section 9
    test fails if they ever stop agreeing.
    """
    sites = sites or config.load_sites()
    factors = {s["code"]: float(s["size_factor"]) for s in sites["sites"]}
    total = sum(factors.values())
    if total <= 0:
        raise ValueError("site size factors must sum to something positive")
    return pd.Series({code: value / total for code, value in factors.items()})


def volume_by_site_from_work(work, assumptions=None):
    """The same shares, measured from the items that actually travel.

    Used to CHECK the choice, not to make it. If this ever disagrees with
    the size-factor ranking about which site should be the hub, the model
    should say so rather than quietly carry two definitions of volume.
    """
    assumptions = assumptions or config.load_assumptions()
    codes = delivery_work_types(assumptions) or moved_work_types(assumptions)
    rows = work[work["work_type"].isin(codes)]
    if rows.empty:
        raise ValueError(f"no work found for the delivery work types {codes}")
    plan = rows[rows["period"] != "history"] if "period" in rows.columns else rows
    if plan.empty:
        plan = rows
    totals = plan.groupby("site")["work_items"].sum()
    if totals.sum() <= 0:
        raise ValueError("the delivery work types carry no volume to weight by")
    return totals / totals.sum()


def hub_ranking(assumptions=None, sites=None, shares=None):
    """Every candidate site, by volume-weighted delivery days (spec 7).

    The whole table rather than the winner, because the runner-up is part
    of what the scenario reports: if two sites are a hair apart, the
    choice is not really a finding, and a reader should be able to see
    that for themselves.
    """
    assumptions = assumptions or config.load_assumptions()
    sites = sites or config.load_sites()
    if shares is None:
        shares = volume_by_site(sites)
    rows = []
    for candidate in (s["code"] for s in sites["sites"]):
        weighted = sum(
            share * delivery_days(candidate, site, assumptions, sites)
            for site, share in shares.items()
        )
        rows.append(
            {
                "site": candidate,
                "cluster": cluster_of(sites)[candidate],
                "volume_share": float(shares.get(candidate, 0.0)),
                "weighted_delivery_days": float(weighted),
            }
        )
    return (
        pd.DataFrame(rows)
        .sort_values(["weighted_delivery_days", "site"])
        .reset_index(drop=True)
    )


def choose_hub(assumptions=None, sites=None, shares=None):
    """(hub, runner-up, the full ranking) - spec 7, decided 11/02.

    A stated `site` input wins, so a different hub can be tested, but the
    ranking is still returned: a hub chosen by hand should have to be read
    next to the one the volume would have picked.
    """
    assumptions = assumptions or config.load_assumptions()
    ranking = hub_ranking(assumptions, sites, shares)
    stated = str(settings(assumptions).get("site", "") or "").strip()
    if stated:
        if stated not in set(ranking["site"]):
            raise ValueError(f"the stated hub site {stated!r} is not a site")
        hub = stated
    else:
        hub = str(ranking["site"].iloc[0])
    others = ranking[ranking["site"] != hub]
    runner_up = str(others["site"].iloc[0]) if len(others) else None
    return hub, runner_up, ranking


def hub_site(assumptions=None, sites=None):
    """Just the hub, for the callers that do not need the ranking."""
    return choose_hub(assumptions, sites)[0]


def move_to_hub(rows, hub, assumptions=None):
    """Re-attribute the moved work types' site to the hub (spec 7).

    This is the ONE place the hub exists as far as staffing is concerned,
    and it is deliberately here rather than on the work-volume table.

    The work table's site is where the REQUEST came from, and the onsite
    interval build (4.1) needs it to stay that way - walk-ins and phones
    are still answered at six counters. What moves is where the WORK IS
    DONE, which is the site column on the required-hours rows, because
    that is what becomes a staffing scope.

    Item counts are untouched: a chart retrieved at the hub is the same
    chart. That is the Section 9 hub check.
    """
    codes = set(moved_work_types(assumptions))
    if not codes:
        return rows
    out = rows.copy()
    out.loc[out["work_type"].isin(codes), "site"] = hub
    return out


def delivery_days_by_site(hub, assumptions=None, sites=None):
    """{requesting site: delivery days} for this hub."""
    sites = sites or config.load_sites()
    return {
        s["code"]: delivery_days(hub, s["code"], assumptions, sites)
        for s in sites["sites"]
    }


def weighted_delivery_days(hub, assumptions=None, sites=None, shares=None):
    """The network's volume-weighted delivery days for this hub.

    What gets added to a hub-retrieved step's days of inventory. It is an
    average over requesting sites because the requesting site is gone by
    then - the queue is the hub's - and an average is the right figure
    anyway: the turnaround this feeds is already a volume-weighted mean
    across the stage (4.4), so a constant added to the step is exactly a
    volume-weighted delivery time added to the stage.
    """
    assumptions = assumptions or config.load_assumptions()
    sites = sites or config.load_sites()
    if shares is None:
        shares = volume_by_site(sites)
    days = delivery_days_by_site(hub, assumptions, sites)
    return float(sum(share * days[site] for site, share in shares.items()))


def add_delivery_to_turnaround(frame, hub, assumptions=None, sites=None):
    """Add the delivery days to every hub-retrieved step (spec 7, item 3).

    Added to DAYS OF INVENTORY, not to the goal: delivery is extra elapsed
    time the requester waits, and the 5-day promise does not move because
    the records moved. Which is the point - if the goal moved with the
    operating model, the scenario could never fail it.

    Returns (frame with delivery added, the days added) so the report can
    show the delivery component on its own line rather than buried in a
    total.
    """
    assumptions = assumptions or config.load_assumptions()
    codes = set(delivery_work_types(assumptions))
    days = weighted_delivery_days(hub, assumptions, sites)
    out = frame.copy()
    travels = out["work_type"].isin(codes)
    out["delivery_days"] = np.where(travels, days, 0.0)
    out["days_of_inventory"] = out["days_of_inventory"] + out["delivery_days"]
    return out, days


def collapse_headcount_to_hub(mapped, assumptions=None, sites=None):
    """Move the Records Specialists to the hub instead of deleting them.

    THE BUG THIS FIXES, found 11/02 and worth keeping written down.

    Making Records Specialists a one-site role is what moves their work
    (see `records_specialist_scopes`), but a scenario does NOT re-tune the
    opening roster (spec 7, 10/27) - it keeps the baseline's starting
    headcount so the gap reports what the change costs. Those two rules
    met badly: the roster still said 3 people at each of six sites, the
    role now had one scope, and the five non-hub entries were simply
    dropped. Three people were left holding the whole network's retrieval,
    and the scenario reported $13.9M, 151 hires and a 28-FTE peak gap -
    a transition cost that was pure artefact.

    A hub transition re-bases people, it does not make them redundant. So
    the baseline's Records Specialists are SUMMED onto the hub: same
    eighteen people, one address. Whether the hub then needs eighteen is
    the question the scenario is asking, and it is answered by the gap and
    the cost, not by quietly losing fifteen of them first.
    """
    assumptions = assumptions or config.load_assumptions()
    if not enabled(assumptions):
        return mapped
    role = "records_specialist"
    if role not in mapped:
        return mapped
    hub = hub_site(assumptions, sites)
    out = dict(mapped)
    out[role] = {hub: float(sum(mapped[role].values()))}
    return out


def records_specialist_scopes(assumptions=None, sites=None):
    """Where Records Specialists sit under this scenario: the hub alone.

    Spec 7: "the 2-per-site floor no longer applies at the other sites."
    The cleanest way to say that in this model is that the role stops
    being a six-site role and becomes a one-site role - then the floor,
    the opening roster, the shrinkage draw and the cluster-borrow logic
    all follow without any of them needing to know a hub exists. The
    cluster borrow in particular: a role with one scope has nobody to
    borrow from, which is correct and needed no special case.
    """
    return [hub_site(assumptions, sites)]
