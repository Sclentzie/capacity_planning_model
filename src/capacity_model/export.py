def _wrapped_height(text, width, points=13.5):
    """Row height for wrapped text, rather than a guessed constant.

    Excel does not auto-fit a wrapped row that has an explicit height, and
    leaving the height alone truncates the one-line findings to a line and
    a half. So the height is computed from the text and the column it sits
    in - roughly one line per `width` characters, which is close enough at
    10pt Arial and errs generous.
    """
    lines = max(1, -(-len(str(text)) // max(1, int(width))))
    return points * lines + 4


def _put(sheet, cell, value, font=BODY_FONT, number_format=None, alignment=None):
    """One cell, always with a font set.

    Every write goes through here so no cell can be left in Calibri by
    being added later - which is exactly how a workbook ends up in two
    fonts.
    """
    target = sheet[cell]
    target.value = value
    target.font = font
    if number_format:
        target.number_format = number_format
    if alignment:
        target.alignment = alignment
    return target


