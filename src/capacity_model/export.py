# The three ways an automated item comes back to a person (spec 5.5).
LOOP_KINDS = ("exception", "qa_sample", "sign_off")


def plan_week(week_index, assumptions):
    """Plan week 1..52 from the model's absolute week index.

    The model counts weeks from the start of the generated HISTORY, which
    is right for a forecast and wrong for a reader: nobody plans in week
    171. Every tab shows plan weeks, and says so.
    """
    return int(week_index) - int(assumptions["calendar"]["history_weeks"]) + 1


def _week_starts(run):
    """week_index -> the Monday it starts, as a plain date string."""
    prepared = run["prepared"]
    return {
        week: str(monday)[:10]
        for week, monday in zip(prepared["weeks"], prepared["mondays"])
    }


def _weekly_onsite(run):
    """The onsite DAILY frame rolled up to the week (spec 4.2, 6.2).

    Hours ADD across the five days. Service levels do not: a service level
    is the share of contacts answered in time, so the week's figure is the
    volume-weighted average rather than the mean of five daily
    percentages. Monday carries 23% of the week's calls, so a straight
    mean would quietly overweight Friday - the day the counter is least
    busy and the service level looks best.
    """
    onsite = run["onsite"]
    grouped = onsite.groupby(["week_index", "role", "site"], as_index=False).agg(
        available_hours=("available_hours", "sum"),
        uncovered_hours=("uncovered_hours", "sum"),
    )
    # The weighted averages are built explicitly rather than inside agg,
    # because a weighted average needs two columns at once.
    weights = []
    for (week, role, site), group in onsite.groupby(["week_index", "role", "site"]):
        calls = group["calls"].sum()
        walk_ins = group["walk_ins"].sum()
        weights.append(
            {
                "week_index": week,
                "role": role,
                "site": site,
                "phone_service_level": (
                    float((group["service_level_phones_after"] * group["calls"]).sum() / calls)
                    if calls > 0 else float("nan")
                ),
                "walk_in_service_level": (
                    float((group["service_level_walk_ins_after"] * group["walk_ins"]).sum() / walk_ins)
                    if walk_ins > 0 else float("nan")
                ),
            }
        )
    grouped = grouped.merge(
        pd.DataFrame(weights), on=["week_index", "role", "site"], how="left"
    )
    return grouped.rename(columns={"site": "scope"})


def capacity_plan_table(run, assumptions=None):
    """Per scope, role and week: what was needed, what was there, what it cost.

    The SPINE is the weekly gap frame, because it is the only table the
    model already produces that carries all fifteen (role, scope) pairs -
    the six onsite sites and the three back-office teams, one of which is
    itself per site. Everything else is merged onto it, so no row can
    appear here that the gap calculation did not produce.
    """
    assumptions = assumptions or config.load_assumptions()

    table = run["gap_fte"][
        ["week_index", "role", "scope", "required_hours", "covered_hours",
         "short_fte", "surplus_fte"]
    ].copy()

    # Cost, overtime and paid headcount are at this grain for every role.
    table = table.merge(
        run["role_cost"][
            ["week_index", "role", "scope", "paid_headcount", "overtime_hours",
             "total_cost"]
        ],
        on=["week_index", "role", "scope"],
        how="left",
    )

    # Available and uncovered hours come from two places, because the two
    # halves of the operation are planned differently: the back office by
    # week (spec 6.2, decided 10/26) and the counter by DAY, since a
    # walk-in cannot wait until Thursday.
    back_office = run["cost"][
        ["week_index", "role", "scope", "available_hours", "uncovered_hours",
         "days_of_inventory_after"]
    ]
    onsite = _weekly_onsite(run)[
        ["week_index", "role", "scope", "available_hours", "uncovered_hours",
         "phone_service_level", "walk_in_service_level"]
    ]

    table = table.merge(back_office, on=["week_index", "role", "scope"], how="left")
    table = table.merge(
        onsite, on=["week_index", "role", "scope"], how="left",
        suffixes=("", "_onsite"),
    )
    for column in ("available_hours", "uncovered_hours"):
        table[column] = table[column].fillna(table[f"{column}_onsite"])
        table = table.drop(columns=[f"{column}_onsite"])

    starts = _week_starts(run)
    table["plan_week"] = [plan_week(week, assumptions) for week in table["week_index"]]
    table["week_start"] = [starts.get(week, "") for week in table["week_index"]]

    return table.sort_values(["plan_week", "role", "scope"]).reset_index(drop=True)


