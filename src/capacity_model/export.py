"""Excel workbook export (spec Section 8).

Session 6. All data is SYNTHETIC, generated by this model.

THE WFM IDEA
------------
A capacity plan only matters if the people who act on it can open it.
Every number in this model is already correct and already tested; none of
that reaches a regional director who does not run Python. This writes the
ten tabs spec Section 8 names - Summary, Capacity Plan, Capacity Ledger,
Capacity Scenarios, Next Dollar, Coverage Events, Non-Digital Tracker,
Hiring Plan, Forecast, Assumptions - so the plan can be read, argued with
and forwarded.

VALUES OR FORMULAS: THE ONE DESIGN DECISION
-------------------------------------------
Decided 11/03 (spec Section 10, "Workbook design"). A workbook can be
written two ways and both are wrong on their own.

All VALUES is a dead report. A leader who wants to know what the hub
costs against the baseline has to subtract two cells by hand, and nobody
does, so the comparison never gets made.

All FORMULAS is a second model, written in Excel, by whoever wrote the
exporter. It will disagree with the Python one eventually, and when it
does the spreadsheet wins the argument because it is the thing in the
room.

So: the model writes every MEASURE as a value, which is what lets the
Section 9 check tie the workbook to the model to the cent; and Excel
computes every DIFFERENCE and every TOTAL as a live formula, from those
values. Nothing is computed twice in two languages. The all-in cost is a
formula over written labour and machine, which makes spec 6.4's whole
point - that one of those numbers alone misleads - visible in the
spreadsheet rather than asserted in a note.

The Summary holds no numbers of its own at all. Every figure on it is a
reference into Capacity Scenarios, so the two tabs cannot drift apart and
a leader who edits a scenario's measure sees the headline move.

WHY THERE IS NO RUN TIMESTAMP
-----------------------------
A wall-clock date in the file would make two runs of a fixed-seed model
produce different workbooks, which would be the one place in the
repository where that is not true. The header carries the PLAN WINDOW
instead - the thing a reader actually needs to know - and the workbook is
byte-stable for a given set of inputs.
"""

