"""Spec Section 9, Session 3: the Erlang C reference case and its guards.

    - Erlang C reference case, worked by Siri by hand or in Excel first:
      100 calls in 30 minutes, AHT 180 sec, so A = 10 Erlangs. Expected:
      13 staff gives 79.6% (misses), 14 staff gives 88.8% and wait
      probability 17.4%. Code must match to 0.1 point.

The hand calculation came first and the code was written to meet it, which is
the only order that makes a reference case worth anything. The spec asks for
0.1 of a point; the values below are pinned to six decimals instead, because
once the arithmetic is right there is no reason to accept less.

Everything else here exists to stop the reference case from being the only
thing that holds. A function can match five numbers exactly and still go
backwards at high traffic, ignore the occupancy cap, or crash on an
understaffed interval.
"""

import math

import pytest

from capacity_model import config, erlang

# ---------------------------------------------------------------------------
# Siri's hand calculation, docs/validation/erlang_hand_check.xlsx, 10/22.
# 100 calls per half-hour, 180-second handle time, 20-second answer target,
# so A = 100 x 180 / 1800 = 10 Erlangs.
# These are her Excel values, transcribed. They are not generated by this
# code, and test_hand_check_constants_match_the_workbook proves it.
# ---------------------------------------------------------------------------
HAND_CHECK_CALLS = 100
HAND_CHECK_HANDLE_TIME = 180
HAND_CHECK_INTERVAL = 1800
HAND_CHECK_TARGET = 20
HAND_CHECK_TRAFFIC = 10.0

HAND_CHECK_SERVICE_LEVEL = {
    11: 0.389614,
    12: 0.640158,
    13: 0.795595,
    14: 0.888350,
    15: 0.941453,
}
HAND_CHECK_REQUIRED_STAFF_AT_80 = 14

WORKBOOK = "docs/validation/erlang_hand_check.xlsx"


@pytest.fixture(scope="module")
def live_queues():
    return config.load_assumptions()["live_queues"]


# ---------------------------------------------------------------------------
# 1. The hand check
# ---------------------------------------------------------------------------


def test_traffic_matches_the_hand_check():
    """A = arrivals x handle time / interval (spec 4.1). 100 x 180 / 1800 = 10."""
    assert erlang.traffic(
        HAND_CHECK_CALLS, HAND_CHECK_HANDLE_TIME, HAND_CHECK_INTERVAL
    ) == pytest.approx(HAND_CHECK_TRAFFIC, abs=1e-12)


@pytest.mark.parametrize("staff,expected", sorted(HAND_CHECK_SERVICE_LEVEL.items()))
def test_service_level_matches_the_hand_check(staff, expected):
    """Six decimals against Siri's Excel, for every staff level she worked."""
    measured = erlang.service_level(
        staff, HAND_CHECK_TRAFFIC, HAND_CHECK_TARGET, HAND_CHECK_HANDLE_TIME
    )
    assert round(measured, 6) == expected


def test_required_staff_matches_the_hand_check(live_queues):
    """13 misses 80% and 14 clears it, so the answer is 14 (spec 9).

    The occupancy cap is not binding here - 10 Erlangs over 14 people is 71%
    busy - so this is the service level deciding on its own.
    """
    staff = erlang.required_staff(
        HAND_CHECK_TRAFFIC,
        HAND_CHECK_TARGET,
        HAND_CHECK_HANDLE_TIME,
        service_level_goal=0.80,
        occupancy_cap=live_queues["occupancy_cap"],
    )
    assert staff == HAND_CHECK_REQUIRED_STAFF_AT_80

    assert HAND_CHECK_SERVICE_LEVEL[13] < 0.80, "13 must miss the goal"
    assert HAND_CHECK_SERVICE_LEVEL[14] >= 0.80, "14 must clear it"
    assert erlang.occupancy(14, HAND_CHECK_TRAFFIC) < live_queues["occupancy_cap"]


def test_wait_probability_matches_the_spec_reference():
    """Spec 9 quotes 17.4% wait probability at 14 staff."""
    waiting = erlang.probability_of_waiting(14, HAND_CHECK_TRAFFIC)
    assert round(waiting, 3) == 0.174


def test_hand_check_constants_match_the_workbook():
    """The constants above must be Siri's numbers, not ones this code made.

    A reference case copied out of the thing it is checking proves nothing.
    This reads the workbook and confirms the hard-coded values came from it,
    so the two can never drift apart unnoticed.
    """
    openpyxl = pytest.importorskip("openpyxl")
    path = config.resolve_path(WORKBOOK)
    if not path.exists():
        pytest.skip(f"{WORKBOOK} not present")

    sheet = openpyxl.load_workbook(path, data_only=True).worksheets[0]
    rows = list(sheet.iter_rows(values_only=True))

    inputs = {row[0]: row[1] for row in rows if isinstance(row[0], str)}
    assert inputs["Calls per interval"] == HAND_CHECK_CALLS
    assert inputs["Handle time (seconds)"] == HAND_CHECK_HANDLE_TIME
    assert inputs["Interval length (seconds)"] == HAND_CHECK_INTERVAL
    assert inputs["Answer target (seconds)"] == HAND_CHECK_TARGET
    assert inputs["Traffic A (Erlangs)"] == HAND_CHECK_TRAFFIC

    # Numeric rows are: staff | Erlang B | Erlang C | SL | occupancy
    for row in rows:
        if not isinstance(row[0], int):
            continue
        staff, blocking, waiting, level, busy = row[:5]
        assert round(level, 6) == HAND_CHECK_SERVICE_LEVEL[staff]
        assert erlang.erlang_b(staff, HAND_CHECK_TRAFFIC) == pytest.approx(blocking, abs=1e-12)
        assert erlang.probability_of_waiting(staff, HAND_CHECK_TRAFFIC) == pytest.approx(
            waiting, abs=1e-12
        )
        assert erlang.occupancy(staff, HAND_CHECK_TRAFFIC) == pytest.approx(busy, abs=1e-12)


# ---------------------------------------------------------------------------
# 2. Adding staff never lowers service level
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("offered", [0.5, 2.0, 10.0, 47.3, 120.0, 500.0])
def test_adding_staff_never_lowers_service_level(offered):
    """Monotonicity. Without it, the search in required_staff is meaningless.

    required_staff stops at the first staff count that clears the goal. That
    is only the smallest adequate team if service level rises with every
    person added - otherwise a later, smaller-looking option could be better
    and the search would walk straight past it.
    """
    previous = -1.0
    for staff in range(0, math.ceil(offered) + 40):
        level = erlang.service_level(staff, offered, 20, 180)
        assert level >= previous - 1e-12, f"service level fell at {staff} staff"
        assert 0.0 <= level <= 1.0
        previous = level


@pytest.mark.parametrize("offered", [2.0, 10.0, 120.0])
def test_adding_staff_never_raises_the_wait_probability_or_occupancy(offered):
    """The same monotonicity from the other two angles."""
    waits = [erlang.probability_of_waiting(n, offered) for n in range(1, 60)]
    assert waits == sorted(waits, reverse=True)

    busy = [erlang.occupancy(n, offered) for n in range(1, 60)]
    assert busy == sorted(busy, reverse=True)


def test_an_understaffed_queue_scores_zero_rather_than_crashing():
    """Staff at or below the traffic returns 0%, not an error.

    The spec formula divides by (N - A), which is zero at N = A and negative
    below it. A staffing search has to be able to ask about understaffed
    options, so those return "this serves nobody" instead of blowing up.
    """
    for staff in (0, 1, 5, 9, 10):
        assert erlang.service_level(staff, 10.0, 20, 180) == 0.0
        assert erlang.probability_of_waiting(staff, 10.0) == 1.0

    # And the first stable staffing is strictly better than zero.
    assert erlang.service_level(11, 10.0, 20, 180) > 0.0


# ---------------------------------------------------------------------------
# 3. The occupancy cap is binding
# ---------------------------------------------------------------------------


def test_the_occupancy_cap_can_beat_the_service_level(live_queues):
    """A case where the goal alone would understaff the queue.

    10 Erlangs, an 8-minute handle time and a 10-minute target: 11 people
    already clear an 80% goal (80.46%), but they would be 90.9% busy. The cap
    refuses that and buys a twelfth person, taking occupancy to 83.3%.

    This is the common shape in a small queue. Service level is a customer
    measure and occupancy is a people measure, and the plan has to pass both.
    """
    cap = live_queues["occupancy_cap"]
    offered, target, handle_time, goal = 10.0, 600, 480, 0.80

    ignoring_cap = erlang.required_staff(offered, target, handle_time, goal, occupancy_cap=1.0)
    with_cap = erlang.required_staff(offered, target, handle_time, goal, occupancy_cap=cap)

    assert ignoring_cap == 11
    assert with_cap == 12, "the cap should force one more person than the goal needs"
    assert with_cap > ignoring_cap

    assert erlang.service_level(11, offered, target, handle_time) >= goal
    assert erlang.occupancy(11, offered) > cap, "11 staff must breach the cap"
    assert erlang.occupancy(12, offered) <= cap


def test_the_chosen_staff_count_always_satisfies_both_constraints(live_queues):
    """Whichever constraint binds, the answer must clear both of them."""
    cap = live_queues["occupancy_cap"]
    for offered in (0.4, 1.0, 3.2, 10.0, 55.0, 300.0):
        for goal, target, handle_time in ((0.80, 20, 180), (0.90, 600, 480)):
            staff = erlang.required_staff(offered, target, handle_time, goal, cap)
            assert erlang.occupancy(staff, offered) <= cap + 1e-12
            assert erlang.service_level(staff, offered, target, handle_time) >= goal - 1e-12
            if staff > 1:
                one_fewer = staff - 1
                fails = (
                    erlang.occupancy(one_fewer, offered) > cap + 1e-12
                    or erlang.service_level(one_fewer, offered, target, handle_time)
                    < goal - 1e-12
                )
                assert fails, f"{staff} is not the SMALLEST adequate team at A={offered}"


# ---------------------------------------------------------------------------
# 4. Stability at high traffic
# ---------------------------------------------------------------------------


def test_five_hundred_erlangs_stays_finite_and_sensible(live_queues):
    """The reason Erlang B's recursion is used instead of A^N / N!.

    At 500 Erlangs the textbook formula needs 500^N and N!, and both overflow
    a float long before they can cancel. Carrying only the ratio keeps every
    step inside [0, 1], so this returns an answer rather than inf or nan.

    The answer itself is informative: the occupancy cap binds hard at this
    size. 510 people already deliver 80% in 20 seconds, but the cap will not
    accept 98% busy and pushes the team to 589.
    """
    cap = live_queues["occupancy_cap"]
    offered = 500.0

    blocking = erlang.erlang_b(600, offered)
    waiting = erlang.probability_of_waiting(600, offered)
    level = erlang.service_level(600, offered, 20, 180)
    for value in (blocking, waiting, level):
        assert math.isfinite(value)
        assert 0.0 <= value <= 1.0

    ignoring_cap = erlang.required_staff(offered, 20, 180, 0.80, occupancy_cap=1.0)
    with_cap = erlang.required_staff(offered, 20, 180, 0.80, occupancy_cap=cap)
    assert ignoring_cap == 510
    assert with_cap == 589
    assert erlang.occupancy(with_cap, offered) <= cap


def test_the_big_queue_needs_proportionally_fewer_people_than_small_ones():
    """The pooling effect, which is the whole teaching note in spec 4.1.

    Ten separate 10-Erlang queues cost more people than one 100-Erlang queue
    at the same service level, because each small queue has to carry its own
    cushion against randomness. This is what the centralized-phones scenario
    in spec 7 goes on to measure, so it is worth pinning now.

    Run without the occupancy cap, which would otherwise set a floor
    proportional to traffic and hide the effect.
    """
    small = erlang.required_staff(10.0, 20, 180, 0.80, occupancy_cap=1.0)
    pooled = erlang.required_staff(100.0, 20, 180, 0.80, occupancy_cap=1.0)

    assert pooled < small * 10, f"{pooled} pooled vs {small * 10} across ten queues"
    assert erlang.occupancy(pooled, 100.0) > erlang.occupancy(small, 10.0)


