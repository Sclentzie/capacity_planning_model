"""The doorway: inputs in, results out (spec Section 8, decided 11/09).

Session 7. One function the dashboard calls, and the same function any
later tool would call:

    api.run({"overrides": {"scenario": {"demand_multiplier": 1.15}}})

WHY A DOORWAY AT ALL. The workbook and the dashboard answer the same
questions, and the fastest way to make them disagree is to let each one
reach into the model and assemble its own figures. Then a column is a
plan-year sum in one and a mean in the other, and nobody can say which is
wrong. So every caller comes through here, and the detail tables this
returns are built by the SAME functions that write the workbook's tabs
(export.capacity_plan_table and friends). The dashboard cannot hold a
number the workbook does not, because there is only one place the numbers
are made.

WHAT IT REFUSES. The overrides are validated by
scenarios.scenario_from_mapping and merged by scenarios.merge_overrides -
the same strict merge a YAML file goes through. An unknown key is an
error, not a no-op. That matters more here than in a file: a dashboard
control that quietly names a key the model does not have would hand back
the baseline, and a reader would see a scenario that "made no difference"
rather than a scenario that never ran.

TWO SPEEDS (decided 11/09). The 21 scenarios in scenarios/ are run once
and saved, so the dashboard loads them instantly instead of spending eight
minutes on every page view. A build-your-own run goes through this door on
demand and takes about half a minute. The saved file is the only generated
file this repository commits, and tests/test_api.py re-runs the whole
model and compares every cell, so it cannot go stale in silence.

Run it (writes the saved results file):
    .venv\\Scripts\\python -m capacity_model.api
"""

import gzip
import hashlib
import json
import time

import pandas as pd

from . import config, export, scenarios

# What an on-demand run is called when the caller does not name it. A
# label, not a model input - every number still comes from the YAML.
CUSTOM_RUN_KEY = "custom"
CUSTOM_RUN_NAME = "Custom run"
NOTHING_CHANGED = "Nothing; the baseline inputs unchanged"

# A run somebody builds in the dashboard is a CHOICE: they are asking
# whether something is worth doing. A risk is something that happens to
# the operation and a sensitivity varies another run, and neither is what
# a control panel produces. A caller who means one of those says so.
CUSTOM_RUN_KIND = scenarios.KIND_CHOICE

# The headline measures, each with the workbook's own column header, so a
# figure is called the same thing in the dashboard as on the tab. The
# headers are checked against export.SCENARIO_COLUMNS by a test rather
# than trusted to stay in step by hand.
COMPARISON_MEASURES = (
    ("Scenario", "scenario"),
    ("All-in cost", "total_cost"),
    ("Labour cost", "labour_cost"),
    ("Machine cost", "machine_cost"),
    ("Network required FTE", "network_required_fte"),
    ("Overtime hours", "overtime_hours"),
    ("Uncovered hours", "uncovered_hours"),
    ("Requester turnaround, mean days", "mean_projected_turnaround_days"),
    ("Weeks over the 5-day goal", "weeks_over_turnaround_goal"),
)

# The detail frames every run carries, in the order a reader would open
# them. Named here so the saver, the loader and the tests all agree on
# what a result holds instead of each listing its own set.
DETAIL_TABLES = ("plan", "turnaround", "cost_lines", "hiring", "surplus")

SYNTHETIC_LABEL = (
    "SYNTHETIC - every figure is generated by capacity_model from the "
    "fixed seed in assumptions.yaml. Northbrook Records Services is "
    "fictional. No real company, patient or employee data."
)

# The input files a saved result was built from. Fingerprinted so the app
# can say "these results came from different inputs" without re-running
# the model; the real guard is the test that recomputes every cell.
INPUT_FILES = (
    config.ASSUMPTIONS_FILE,
    config.SITES_FILE,
    config.SKILLS_FILE,
)


# ---------------------------------------------------------------------------
# One run
# ---------------------------------------------------------------------------


def describe_overrides(mapping):
    """A plain-language "what it changes" for a run nobody named.

    Built from the keys the caller actually declared, so the label cannot
    claim a change the run did not make.
    """
    scenario = {
        "overrides": (mapping or {}).get("overrides") or {},
        "site_overrides": (mapping or {}).get("site_overrides") or {},
    }
    # Drop the three IDENTITY keys declared_keys appends - and only those.
    # The model's own scenario block lives at overrides.scenario.*, so
    # filtering every "scenario." prefix would throw away the real change:
    # a run with demand_multiplier 1.15 reported "Nothing" until this was
    # narrowed to the exact three.
    identity = {f"scenario.{key}" for key in scenarios.IDENTITY_KEYS}
    keys = [
        key
        for key in scenarios.declared_keys(scenario)
        if key not in identity
    ]
    keys += scenarios.declared_site_keys(scenario)
    if not keys:
        return NOTHING_CHANGED
    return "Changes " + ", ".join(sorted(keys))


def scenario_from_overrides(mapping=None, baseline=None, key=CUSTOM_RUN_KEY):
    """Turn a caller's overrides into a scenario the engine can run.

    The identity block a YAML file always carries - name, starts week,
    what it changes - is optional here, because a dashboard control panel
    has no file header. Anything missing is filled from assumptions.yaml's
    own scenario block, so the default starts week is the baseline's own
    input rather than a number invented in this module.
    """
    baseline = baseline or config.load_assumptions()
    mapping = dict(mapping or {})

    header = dict(mapping.get("scenario") or {})
    header.setdefault("name", CUSTOM_RUN_NAME)
    header.setdefault("starts_week", baseline["scenario"]["starts_week"])
    header.setdefault("what_it_changes", describe_overrides(mapping))
    header.setdefault("kind", CUSTOM_RUN_KIND)
    mapping["scenario"] = header

    return scenarios.scenario_from_mapping(mapping, key, label=header["name"])


def run(overrides=None, *, baseline=None, sites=None, key=CUSTOM_RUN_KEY):
    """Run the model on one set of overrides and return its results.

    `overrides` has the same shape as a file in scenarios/: a `scenario`
    block (optional here), an `overrides` block for assumptions.yaml and a
    `site_overrides` block for sites.yaml. Unknown keys are refused.
    """
    baseline = baseline or config.load_assumptions()
    sites = sites if sites is not None else config.load_sites()
    scenario = scenario_from_overrides(overrides, baseline, key)
    built = scenarios.run_scenario(scenario, baseline, sites)
    return results(built, key=key)


def results(built, key=None):
    """Shape one built run into the bundle every caller downstream reads.

    The summary is scenarios.summarise - the same row the workbook's
    comparison tab is made of. The detail frames are the workbook's own
    table builders. Nothing here computes a figure of its own; this
    function only decides what a caller gets handed.
    """
    assumptions = built["assumptions"]
    return {
        "key": key or built["scenario"].get("key") or CUSTOM_RUN_KEY,
        "name": built["scenario"]["name"],
        "starts_week": built["scenario"]["starts_week"],
        "what_it_changes": built["scenario"]["what_it_changes"],
        "kind": built["scenario"]["kind"],
        "summary": scenarios.summarise(built, assumptions, built["sites"]),
        # Weekly gap by site and role, with the cost, service levels and
        # days of inventory already beside it: the Capacity Plan tab.
        "plan": export.capacity_plan_table(built, assumptions),
        "turnaround": turnaround_table(built, assumptions),
        "cost_lines": cost_lines_table(built, assumptions),
        "hiring": export.hiring_plan_table(built, assumptions),
        # The other half of 6.5. A hiring view that only ever says "hire"
        # is a budget request, and the Hiring Plan tab shows both - so the
        # dashboard gets both too, or it would contradict the workbook.
        "surplus": export.surplus_table(built, assumptions),
        "machine_spend": scenarios.machine_spend(built),
    }


def turnaround_table(built, assumptions=None):
    """Turnaround by plan week, with its five stages (spec 4.4).

    Not a workbook tab - the Summary carries the mean and the count of
    weeks over goal - so the week-by-week shape is shaped here. It is
    plan.weekly_turnaround's own frame with the week labelled the way
    every tab labels it, so a week means the same thing in both places.
    """
    assumptions = assumptions or built["assumptions"]
    table = built["turnaround"].copy()
    starts = export._week_starts(built)
    table["plan_week"] = [
        export.plan_week(week, assumptions) for week in table["week_index"]
    ]
    table["week_start"] = [starts.get(week, "") for week in table["week_index"]]
    goal = assumptions["backlog"]["overall_turnaround_goal_days"]
    table["over_goal"] = table["turnaround_days"] > goal
    front = ["plan_week", "week_start"]
    rest = [column for column in table.columns if column not in front]
    return table[front + rest].sort_values("plan_week").reset_index(drop=True)


# (cost line, where the money goes). Labour is split into regular pay and
# overtime because they are different decisions; the machine's invoice is
# split into its three real parts (spec 5.4).
LABOUR_LINES = (
    ("Regular pay", "regular_cost", None),
    ("Overtime", "overtime_cost", "overtime_hours"),
)
MACHINE_LINES = (
    ("Automation, per-item fee", "item_cost"),
    ("Automation, setup over the plan year", "setup_cost"),
    ("Automation, shared platform fee", "platform_cost"),
)
MACHINE_BASIS = "Automation"


def cost_lines_table(built, assumptions=None):
    """Every line of the plan-year bill, labour and machine together.

    The point of the table is that it ADDS UP: the amount column sums to
    the all-in cost on the comparison row, which a test checks to the
    cent. A cost view that nearly reconciles is worse than none, because
    the gap is where a reader stops trusting the rest of it.

    Labour by role, because that is the decision a leader makes. The
    machine's invoice at network scope, because the platform fee is one
    shared fee and splitting it per site would invent a number (5.4).
    """
    assumptions = assumptions or built["assumptions"]
    rows = []
    role_cost = built["role_cost"]
    for role, group in role_cost.groupby("role", sort=True):
        for line, amount_column, hours_column in LABOUR_LINES:
            rows.append(
                {
                    "cost_line": line,
                    "basis": role,
                    "hours": (
                        float(group[hours_column].sum())
                        if hours_column is not None
                        else float("nan")
                    ),
                    "amount": float(group[amount_column].sum()),
                }
            )

    spend = scenarios.machine_spend(built)
    for line, amount_column in MACHINE_LINES:
        rows.append(
            {
                "cost_line": line,
                "basis": MACHINE_BASIS,
                "hours": float("nan"),
                "amount": float(spend[amount_column]),
            }
        )
    return pd.DataFrame(rows, columns=["cost_line", "basis", "hours", "amount"])


