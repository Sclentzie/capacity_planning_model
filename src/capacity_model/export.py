def forecast_tables(assumptions=None, sites=None):
    """The whole of spec 3.2, shaped for the tab.

    Returns the scoreboard, the week-by-week series, and the headline
    facts about the choice. Built by calling forecast.run, which is the
    same path plan generation uses - the workbook never reads a CSV a
    previous run happened to leave behind.
    """
    assumptions = assumptions or config.load_assumptions()
    sites = sites if sites is not None else config.load_sites()
    forward, chosen, both, history = forecast.run(assumptions, sites)

    live = assumptions["forecast"]["calendar_events"]["enabled"]
    live_label = "calendar_events" if live else "no_calendar_events"

    scores = forecast.scores_table(both)
    scores["chosen"] = [
        "chosen"
        if treatment == live_label and method == chosen["method"]
        and scope == "NETWORK"
        else ""
        for treatment, scope, method in zip(
            scores["treatment"], scores["scope"], scores["method"]
        )
    ]

    cal = assumptions["calendar"]
    holdout = int(cal["holdout_weeks"])
    history_weeks = int(cal["history_weeks"])

    actual = history.groupby(["week_index", "week_start"], as_index=False)[
        "requests"
    ].sum().rename(columns={"requests": "actual_requests"})
    forecast_weekly = forward.groupby(
        ["week_index", "week_start"], as_index=False
    )["forecast_requests"].sum()

    # The holdout predictions, one column per method, so the MAPE above
    # can be checked against the numbers it was computed from.
    predictions = chosen["predictions"].groupby(
        ["week_index", "method"], as_index=False
    )["predicted"].sum()
    wide = predictions.pivot(
        index="week_index", columns="method", values="predicted"
    ).reset_index()

    weeks = pd.concat([actual, forecast_weekly], ignore_index=True)
    weeks = weeks.merge(wide, on="week_index", how="left")
    weeks["week_start"] = weeks["week_start"].astype(str).str[:10]
    weeks["period"] = [
        "forecast" if week >= history_weeks
        else ("holdout" if week >= history_weeks - holdout else "history")
        for week in weeks["week_index"]
    ]
    weeks["history_week"] = [
        None if week >= history_weeks else int(week)
        for week in weeks["week_index"]
    ]
    weeks["plan_week"] = [
        plan_week(week, assumptions) if week >= history_weeks else None
        for week in weeks["week_index"]
    ]
    weeks = weeks.sort_values("week_index").reset_index(drop=True)

    pooled = {
        treatment: result["pooled"].to_dict() for treatment, result in (
            ("no_calendar_events", both[False]), ("calendar_events", both[True])
        )
    }
    facts = {
        "method": chosen["method"],
        "treatment": live_label,
        "holdout_weeks": holdout,
        "history_weeks": history_weeks,
        "pooled": pooled,
        # The two frames the picture is drawn from, carried out alongside
        # the tables. The tab can then draw its own chart from the run it
        # is reporting, instead of hoping a PNG from some earlier run is
        # still lying in the outputs folder.
        "series": {"history": history, "forward": forward},
    }
    return scores, weeks, facts


