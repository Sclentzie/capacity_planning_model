def _loop_hours_by_scope(run):
    """Human-in-the-loop hours per week, role and scope (spec 5.5).

    Automated items come BACK to people three ways - exceptions, the QA
    sample and legal sign-off - and those hours are real staffing. They
    are already on the required-hours table under their own work kind, so
    this pulls them back out rather than recomputing them.

    The required table is per SITE even for back-office roles, because
    that is where the request arrived. The ledger is per SCOPE, so a
    back-office role's hours are summed up to NETWORK. Which roles those
    are is read off the ledger rather than hard-coded, so a role that
    changes pool in skills.yaml does not need a change here.
    """
    required = run["prepared"].get("required")
    if required is None or "work_kind" not in getattr(required, "columns", []):
        return {}
    loop = required[required["work_kind"].isin(LOOP_KINDS)]
    if not len(loop):
        return {}

    ledger = run["prepared"]["ledger"]["ledger"]
    network_roles = {
        role
        for role, group in ledger.groupby("role")
        if set(group["scope"]) == {NETWORK}
    }
    scope = [
        NETWORK if role in network_roles else site
        for role, site in zip(loop["role"], loop["site"])
    ]
    grouped = (
        loop.assign(scope=scope)
        .groupby(["week_index", "role", "scope"])["required_hours"]
        .sum()
    )
    return {key: float(hours) for key, hours in grouped.items()}


def capacity_ledger_table(run, assumptions=None):
    """Per scope, role and week: how the roster actually moved (spec 5, 6.3).

    The tab that answers "where did the hours come from", which is a
    different question from "were they enough". Headcount at the start of
    the week, who joined, who left, how much of them was productive after
    the training curve and shrinkage - and the human-in-the-loop hours the
    machine hands back, which are staffing like any other hour.
    """
    assumptions = assumptions or config.load_assumptions()

    table = run["prepared"]["ledger"]["ledger"][
        ["week_index", "role", "scope", "starting_headcount", "hires",
         "attrition", "ending_headcount", "ramped_fte", "shrinkage",
         "productive_hours"]
    ].copy()

    table = table.merge(
        run["role_cost"][["week_index", "role", "scope", "overtime_hours"]],
        on=["week_index", "role", "scope"],
        how="left",
    )

    loop = _loop_hours_by_scope(run)
    table["human_in_the_loop_hours"] = [
        loop.get((week, role, scope), 0.0)
        for week, role, scope in zip(
            table["week_index"], table["role"], table["scope"]
        )
    ]

    starts = _week_starts(run)
    table["plan_week"] = [plan_week(week, assumptions) for week in table["week_index"]]
    table["week_start"] = [starts.get(week, "") for week in table["week_index"]]
    return table.sort_values(["plan_week", "role", "scope"]).reset_index(drop=True)


