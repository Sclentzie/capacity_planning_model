# Next Dollar (spec Section 8, 6.6; task 6c)
#
# The tab that answers "where does the next dollar go", and the one place
# in the workbook where a leader is handed a RANKING rather than a
# measurement. So the basis has to be on the tab, not in somebody's head.
#
# PRICED AT THE AI 100% RUN'S VOLUMES, and labelled so on the tab. The
# ranking is not a property of a work type on its own: setup is FIXED and
# the saving SCALES with items, so the fixed cost per item - and therefore
# the order - depends on how many items the machine actually sees. The
# full-program run is the right basis because it is the only one that
# switches every eligible row on, which is the question this table
# answers: if you automated everything, which rows would pay?
#
# RANKED AFTER FIXED COSTS (decided 10/27). A row that saves $1.58 on a
# $2.32 item returns more per dollar spent than one that saves $4 on a $10
# item, and the next dollar should go to the first. Ranking on the
# before-fixed figure would put a low-volume row near the top on the
# strength of a per-item fee it cannot actually achieve.
#
# ON THE EASY-ITEM BASIS (spec 6.6, decided 10/28). The items a machine
# takes are the SIMPLE ones, so the human cost it displaces is what a
# simple item would have cost by hand, not what an average one would. That
# single decision cut the profitable list from six rows to two, and it is
# the reason the human cost per item here is lower than the handle-time
# table would suggest.
#
# W11 AND W24 ARE REPORTED, NOT RANKED. Spec Section 1 pins them to 0%, so
# the machine never touches an item and there is no cost per item to
# divide by. Calling it zero made them look sixty times more profitable
# than anything real and put the two rows automation is FORBIDDEN from
# touching at the top of the ranking. Not measurable is not free, so they
# carry blanks and sort last.
# ---------------------------------------------------------------------------

NEXT_DOLLAR_RUN = "ai_and_automation.yaml"

# Shown where a dimension does not apply to a row, rather than a blank.
NOT_APPLICABLE = "n/a"

NEXT_DOLLAR_COLUMNS = (
    ("Rank", "rank", COUNT, 10, False),
    ("Work type", "work_type", None, 10, False),
    ("Role", "role", None, 19, False),
    ("Medium", "media", None, 14, False),
    ("Handle times folded in", "combinations", COUNT, 11, False),
    ("Plan-year items arriving", "plan_year_items", COUNT, 12, False),
    ("Items actually automated", "automated_items", COUNT, 12, True),
    ("Human cost per item (easy-item basis)", "human_cost_per_item", MONEY_CENTS, 13, False),
    ("Automated cost per item, variable", "automated_cost_per_item", MONEY_CENTS, 13, False),
    ("Fixed cost per item", "fixed_cost_per_item", MONEY_CENTS, 12, False),
    ("Automated cost per item, after fixed",
     "automated_cost_per_item_after_fixed", MONEY_CENTS, 13, False),
    ("Saving per item, after fixed", "savings_per_item_after_fixed",
     MONEY_CENTS, 13, False),
    ("Saving per dollar spent", "savings_per_dollar", PER_DOLLAR, 12, False),
    ("Plan-year saving on the items automated", None, MONEY, 14, True),
    ("Human lead time, weeks", "human_lead_weeks", COUNT, 10, False),
    ("Automation lead time, weeks", "automation_lead_weeks", COUNT, 10, False),
)


def automated_items_by_work_type(automated, assumptions):
    """Items the machine ACTUALLY did over the plan year, per work type.

    The denominator that matters. A work type's plan-year ITEM count is
    every item that arrives; its AUTOMATED count is the small share a
    machine takes - 8% of the eligible simple ones at spec 7.1's defaults.
    Multiplying a per-item saving by the first gives the saving a machine
    would make if it did all the work, which no run of this model has ever
    described.
    """
    if automated is None or not len(automated):
        return {}
    plan_weeks, _mondays = supply.plan_window(assumptions)
    rows = automated[automated["week_index"].isin(plan_weeks)]
    return {
        str(code): float(group["automated_items"].sum())
        for code, group in rows.groupby("work_type")
    }


def next_dollar_table(assumptions=None, sites=None):
    """The ranking, priced at the AI 100% run's volumes (spec 6.6).

    Built through plan.next_dollar's own rebuild path on the merged
    full-program assumptions, so the human side is the one that run
    produces. Found 11/03 the hard way: handing it a required-hours table
    from a different scenario silently repriced every row, and the answer
    looked plausible.

    The required-hours table is built HERE and passed in, rather than
    letting next_dollar build its own, for two reasons: it is the same
    table either way, and this way the automation plan behind it is in
    hand - which is what the plan-year saving has to be multiplied by.
    """
    assumptions = assumptions or config.load_assumptions()
    sites = sites if sites is not None else config.load_sites()
    scenario = scenarios.load_scenario(
        scenarios.scenario_dir(assumptions) / NEXT_DOLLAR_RUN
    )
    merged = scenarios.apply_scenario(scenario, assumptions)
    merged_sites = scenarios.apply_site_overrides(scenario, sites)
    required = backlog.required_hours(merged, merged_sites)
    table = plan.next_dollar(merged, merged_sites, required=required).copy()
    automated_items = automated_items_by_work_type(
        required.get("automation"), merged
    )
    table["automated_items"] = [
        automated_items.get(str(code), 0.0) for code in table["work_type"]
    ]

    # The rank is the row's position in the order plan.next_dollar already
    # sorted into - rows with no measurable figure sort last and are
    # reported without a rank, because ranking a row you cannot price
    # would be the whole mistake this column exists to avoid.
    # A work type whose handle time does not vary by medium carries an
    # empty medium in the model. Written straight through it becomes a
    # BLANK cell, which cannot be told apart from an exporter that failed
    # to write - the same trap the Assumptions tab hit in 6b. "n/a" says
    # the dimension does not apply, which is what the empty string means.
    table["media"] = [
        NOT_APPLICABLE if not str(medium or "").strip() else medium
        for medium in table["media"]
    ]

    ranked = table["savings_per_dollar"].notna()
    table["rank"] = pd.Series(
        range(1, int(ranked.sum()) + 1), index=table.index[ranked]
    )
    # ON THE ITEMS ACTUALLY AUTOMATED, not on every item of that type.
    #
    # Found 11/06 by Siri reading the tab: the total row said the full
    # program would save -$1,459,131, which is the per-item figure times
    # every item that arrives - a world in which the machine does 100% of
    # the work. At spec 7.1's defaults it does about 8% of the eligible
    # simple items, 59,032 of them, and the honest figure is seventeen
    # times smaller.
    #
    # The wrong one was not even conservative in a safe direction: it
    # scaled up a per-row saving AND a per-row loss, so it exaggerated
    # both sides of a ranking whose whole job is to say which rows pay.
    table["saving_on_automated_items"] = (
        table["savings_per_item_after_fixed"] * table["automated_items"]
    )
    return table.reset_index(drop=True)


