# through. Onsite roles are at a site, so their scope is a site code.
# Back-office roles work the queue remotely, so their scope is NETWORK - a
# tier 1 specialist is not AT N2, and inventing a site for them would be a
# fabricated number on the one tab whose job is traceability. The spec's
# "per site, role, and week" is therefore per SCOPE, role and week, and
# the column header says so.
#
# NOT EVERY MEASURE APPLIES TO EVERY ROLE, and the blanks are the honest
# answer rather than a gap:
#
#   SERVICE LEVELS belong to live channels. A phone call or a walk-in is
#     answered in time or it is not, and the measure only exists where
#     somebody is waiting in real time. A back-office queue has no service
#     level; it has days of inventory.
#   DAYS OF INVENTORY is the mirror image - it belongs to work that is
#     ALLOWED to wait, which is the back office. The counter queue is not
#     a backlog.
#
# Writing a zero in either place would read as "measured, and it is zero",
# which is false. A blank reads as "this measure does not exist for this
# row", which is true.
# ---------------------------------------------------------------------------

