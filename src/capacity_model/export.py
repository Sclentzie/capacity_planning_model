def build(result, assumptions=None):
    """Every Section 8 tab, with task 6a's two filled (spec Section 8).

    `result` is what scenarios.run() returns, so the workbook is written
    from the same object the comparison CSV is - there is no second route
    to the numbers and therefore no second answer.
    """
    assumptions = assumptions or config.load_assumptions()
    book = Workbook()
    book.remove(book.active)

    sheets = {}
    for name, description in TABS:
        sheets[name] = book.create_sheet(title=name)

    rows = write_capacity_scenarios(
        sheets["Capacity Scenarios"], result["comparison"], assumptions
    )
    write_summary(sheets["Summary"], rows, assumptions)

    # The four baseline tabs (task 6b). They read the BASELINE run out of
    # the same result object the comparison came from, so the detail and
    # the headline cannot disagree - there is no second route to the
    # numbers and therefore no second answer.
    baseline = result["runs"][BASELINE_KEY]
    write_capacity_plan(sheets["Capacity Plan"], baseline, assumptions)
    write_capacity_ledger(sheets["Capacity Ledger"], baseline, assumptions)
    write_hiring_plan(sheets["Hiring Plan"], baseline, assumptions)
    write_assumptions(sheets["Assumptions"], baseline, assumptions)

    # The last four (task 6c). Next Dollar and Forecast are priced from
    # their own runs rather than from the baseline - the ranking only
    # means anything at the full program's volumes, and the forecast is
    # upstream of every scenario - so they take the assumptions and
    # rebuild, which is what keeps them honest when a default moves.
    sites = baseline.get("sites")
    write_next_dollar(sheets["Next Dollar"], assumptions, sites)
    write_coverage_events(sheets["Coverage Events"], baseline, assumptions)
    write_non_digital_tracker(
        sheets["Non-Digital Tracker"], baseline, assumptions
    )
    write_forecast(sheets["Forecast"], assumptions, sites)

    book.active = book.index(sheets["Summary"])
    return book


def workbook_path(assumptions=None):
    assumptions = assumptions or config.load_assumptions()
    out_dir = config.resolve_path(assumptions["paths"]["outputs_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)
    return out_dir / assumptions["paths"]["workbook_xlsx"]


def write(result, assumptions=None):
    """Build and save, returning the path."""
    assumptions = assumptions or config.load_assumptions()
    path = workbook_path(assumptions)
    build(result, assumptions).save(path)
    return path


def main():
    assumptions, sites, _skills = config.load_all()
    paths = scenarios.list_scenarios(assumptions)
    print(f"Capacity Workbook (spec Section 8): {len(paths)} scenario runs, SYNTHETIC")
    result = scenarios.run(paths, assumptions, sites)
    written = write(result, assumptions)
    print(f"  workbook -> {written}")
    print(f"  tabs filled: {len(BUILT_TABS)} of {len(TABS)}")
    for name, _description in TABS:
        print(f"    {name}")


if __name__ == "__main__":
    main()
