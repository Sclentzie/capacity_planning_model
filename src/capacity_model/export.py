# THE HOURS COLUMNS ARE NOT TOTALLED, and this is the trap on this tab.
#
# Found 11/03 by the tie-out: the SAME uncovered hour is logged twice -
# once on the E2 overtime event, as what was still short after the
# overtime, and again on the E3 event that accepted the gap. Summing the
# column down the log gives 839.9 hours against a true 420.0, which is
# exactly the kind of figure that gets quoted in a meeting and never
# questioned, because it is a total of a column that really is there.
#
# hours_short_before_cover overlaps the same way, and hours_covered mixes
# three different kinds of cover - a borrow, an overtime hour and a
# reprioritisation - which are not interchangeable.
#
# So the log totals only what belongs to exactly ONE event type: the
# travel a borrow caused and the overtime an E2 paid for. The hours are
# totalled in the BY EVENT TYPE block below, where they mean something,
# and that is also where they tie to Capacity Plan.
EVENT_TOTALLED = (
    "travel_hours", "travel_miles", "travel_cost", "overtime_cost",
)

