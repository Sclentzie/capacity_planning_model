SCENARIO_FIRST_DATA_ROW = 5


def _scenario_rows(comparison):
    """The comparison table with the baseline first, then the rest by name.

    The baseline leads because every difference column is measured against
    it, so the row the formulas point at is the row a reader's eye lands on
    first. The rest are alphabetical, which is the only order that does not
    smuggle in an opinion - ranking them by cost would quietly editorialise
    on a tab whose job is to be neutral.
    """
    table = comparison.copy()
    baseline = table[table["scenario"] == "Baseline"]
    if baseline.empty:
        raise ValueError("the comparison table has no Baseline row to difference against")
    rest = table[table["scenario"] != "Baseline"].sort_values("scenario")
    return pd.concat([baseline, rest], ignore_index=True)


def write_capacity_scenarios(sheet, comparison, assumptions):
    """All 21 runs, one row each (spec Section 8, decided 11/03)."""
    rows = _scenario_rows(comparison)
    goal = assumptions["backlog"]["overall_turnaround_goal_days"]

    _put(sheet, "A1", "Capacity Scenarios - SYNTHETIC", TITLE_FONT)
    _put(sheet, "A2", SYNTHETIC, NOTE_FONT)
    _put(
        sheet,
        "A3",
        f"Plan year, {len(rows)} runs. Measures are written by the model; "
        f"all-in cost and every 'vs baseline' column are live Excel "
        f"formulas over them. Costs are stored to the cent and shown to "
        f"the dollar. Turnaround is the requester's view against the "
        f"{goal}-business-day goal.",
        NOTE_FONT,
    )

    for index, (header, _source, _fmt, width) in enumerate(SCENARIO_COLUMNS, start=1):
        letter = get_column_letter(index)
        cell = _put(
            sheet, f"{letter}{SCENARIO_HEADER_ROW}", header, HEADER_FONT,
            alignment=HEADER_ALIGN,
        )
        cell.fill = HEADER_FILL
        sheet.column_dimensions[letter].width = width
    sheet.row_dimensions[SCENARIO_HEADER_ROW].height = 42

    baseline_row = SCENARIO_FIRST_DATA_ROW
    for offset, record in enumerate(rows.itertuples()):
        row = SCENARIO_FIRST_DATA_ROW + offset
        values = record._asdict()
        for header, source, number_format, _width in SCENARIO_COLUMNS:
            letter = SCENARIO_LETTERS[header]
            font = BODY_BOLD if row == baseline_row else BODY_FONT
            if source == "scenario":
                cell = _put(sheet, f"{letter}{row}", values["scenario"], font)
            elif source is not None:
                cell = _put(
                    sheet, f"{letter}{row}", float(values[source]), font,
                    number_format,
                )
            else:
                cell = None  # a formula, written below
            if cell is not None:
                cell.border = UNDERLINE
                if row == baseline_row:
                    cell.fill = BASELINE_FILL

        # The all-in TOTAL, live: labour plus machine. Spec 6.4's point is
        # that neither half alone is the cost of a scenario, and a formula
        # says so in a way a note cannot.
        labour = SCENARIO_LETTERS["Labour cost"]
        machine = SCENARIO_LETTERS["Machine cost"]
        all_in = SCENARIO_LETTERS["All-in cost"]
        cell = _put(
            sheet,
            f"{all_in}{row}",
            f"={labour}{row}+{machine}{row}",
            BODY_BOLD,
            MONEY,
        )
        cell.border = UNDERLINE
        if row == baseline_row:
            cell.fill = BASELINE_FILL

        # Every difference against the baseline row, live. The baseline's
        # own row differences to zero rather than being left blank: a blank
        # reads as "not measured" and zero reads as "measured, and it is
        # the reference".
        for difference, measure in VS_BASELINE:
            here = SCENARIO_LETTERS[difference]
            against = SCENARIO_LETTERS[measure]
            fmt = dict(
                (header, number_format)
                for header, _s, number_format, _w in SCENARIO_COLUMNS
            )[difference]
            cell = _put(
                sheet,
                f"{here}{row}",
                f"={against}{row}-{against}${baseline_row}",
                BODY_FONT,
                fmt,
            )
            cell.border = UNDERLINE
            if row == baseline_row:
                cell.fill = BASELINE_FILL

    sheet.freeze_panes = f"B{SCENARIO_FIRST_DATA_ROW}"
    return rows


