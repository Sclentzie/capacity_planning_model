def machine_week_table(run, assumptions=None):
    """Automated items and uptime per plan week (spec 5.4).

    Empty when the run has no automation, which is the baseline. The empty
    frame is the answer, and the tab writes a sentence instead of 52 rows
    of zeros.
    """
    assumptions = assumptions or config.load_assumptions()
    automated = run["prepared"].get("automated")
    if automated is None or not len(automated):
        return pd.DataFrame(
            columns=["plan_week", "week_start", "automated_items", "uptime",
                     "total_cost"]
        )
    grouped = automated.groupby("week_index", as_index=False).agg(
        automated_items=("automated_items", "sum"),
        uptime=("uptime", "mean"),
        total_cost=("total_cost", "sum"),
    )
    starts = _week_starts(run)
    grouped["plan_week"] = [
        plan_week(week, assumptions) for week in grouped["week_index"]
    ]
    grouped["week_start"] = [starts.get(week, "") for week in grouped["week_index"]]
    return grouped.sort_values("plan_week").reset_index(drop=True)


